/**
 * Buoyancy simulation.
 *
 * weight = object_density * volume * g
 * max_buoyant_force = fluid_density * volume * g   (if fully submerged)
 *
 * Floats when object_density <= fluid_density (submerged_fraction =
 * object_density / fluid_density, buoyant force = weight, net force = 0);
 * otherwise sinks (fully submerged, net force = weight - max_buoyant_force,
 * pulling it down). Like circuits.js and coulombs-law.js, there is no time
 * axis and no run loop: values are recomputed live on every control
 * change. Always computed here, in code -- never fetched from a server and
 * never generated by AI. Mirrors apps/physics/simulations_buoyancy.py
 * exactly (same bounds, same formulas, same gravity constant). This file
 * owns its own physics, SVG and controls; it shares only the registry
 * shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var GRAVITY_MS2 = 9.8;
  var MIN_DENSITY_KG_M3 = 100.0;
  var MAX_DENSITY_KG_M3 = 12000.0;
  var MIN_VOLUME_M3 = 0.001;
  var MAX_VOLUME_M3 = 1.0;

  function clampDensity(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_DENSITY_KG_M3, Math.min(MAX_DENSITY_KG_M3, n));
  }
  function clampVolume(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_VOLUME_M3, Math.min(MAX_VOLUME_M3, n));
  }

  function computeState(objectDensity, fluidDensity, volume) {
    var rhoObject = clampDensity(objectDensity);
    var rhoFluid = clampDensity(fluidDensity);
    var v = clampVolume(volume);

    var weight = rhoObject * v * GRAVITY_MS2;
    var maxBuoyantForce = rhoFluid * v * GRAVITY_MS2;
    var floats = weight <= maxBuoyantForce;

    var submergedFraction, buoyantForce, netForce;
    if (floats) {
      submergedFraction = rhoObject / rhoFluid;
      buoyantForce = weight;
      netForce = 0;
    } else {
      submergedFraction = 1.0;
      buoyantForce = maxBuoyantForce;
      netForce = weight - maxBuoyantForce;
    }

    return {
      objectDensity: rhoObject,
      fluidDensity: rhoFluid,
      volume: v,
      weight: weight,
      maxBuoyantForce: maxBuoyantForce,
      buoyantForce: buoyantForce,
      submergedFraction: submergedFraction,
      floats: floats,
      netForce: netForce
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createBuoyancySim(root, config, lab) {
    var state = {
      objectDensity: clampDensity(readNum(root, "object-density", 600)),
      fluidDensity: clampDensity(readNum(root, "fluid-density", 1000)),
      volume: clampVolume(readNum(root, "volume", 0.05))
    };
    var computed = computeState(state.objectDensity, state.fluidDensity, state.volume);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      object: root.querySelector("[data-object]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      barWeight: root.querySelector("[data-bar-weight]"),
      barBuoyant: root.querySelector("[data-bar-buoyant]"),
      barWeightLabel: root.querySelector("[data-bar-weight-label]"),
      barBuoyantLabel: root.querySelector("[data-bar-buoyant-label]"),
      valueObjectDensity: root.querySelector("[data-value-object-density]"),
      valueFluidDensity: root.querySelector("[data-value-fluid-density]"),
      valueVolume: root.querySelector("[data-value-volume]"),
      valueWeight: root.querySelector("[data-value-weight]"),
      valueBuoyant: root.querySelector("[data-value-buoyant]"),
      valueNet: root.querySelector("[data-value-net]"),
      valueVerdict: root.querySelector("[data-value-verdict]"),
      eqWeight: root.querySelector("[data-eq-weight]"),
      eqBuoyant: root.querySelector("[data-eq-buoyant]"),
      outObjectDensity: root.querySelector("[data-out-object-density]"),
      outFluidDensity: root.querySelector("[data-out-fluid-density]"),
      outVolume: root.querySelector("[data-out-volume]"),
      inputObjectDensity: root.querySelector("[data-input-object-density]"),
      inputFluidDensity: root.querySelector("[data-input-fluid-density]"),
      inputVolume: root.querySelector("[data-input-volume]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.objectDensity, state.fluidDensity, state.volume);
    }

    function setObjectDensity(value) {
      state.objectDensity = clampDensity(value);
      if (el.inputObjectDensity) el.inputObjectDensity.value = String(state.objectDensity);
      if (el.outObjectDensity) el.outObjectDensity.textContent = String(state.objectDensity);
      recompute();
      render();
    }
    function setFluidDensity(value) {
      state.fluidDensity = clampDensity(value);
      if (el.inputFluidDensity) el.inputFluidDensity.value = String(state.fluidDensity);
      if (el.outFluidDensity) el.outFluidDensity.textContent = String(state.fluidDensity);
      recompute();
      render();
    }
    function setVolume(value) {
      state.volume = clampVolume(value);
      if (el.inputVolume) el.inputVolume.value = String(state.volume);
      if (el.outVolume) el.outVolume.textContent = String(state.volume);
      recompute();
      render();
    }
    function reset() {
      setObjectDensity(600);
      setFluidDensity(1000);
      setVolume(0.05);
    }

    function renderScene() {
      var objectSize = 50;
      var waterY = 90;
      var containerBottom = 190;
      var bottomY, topY;
      if (computed.floats) {
        var submergedHeight = objectSize * computed.submergedFraction;
        bottomY = waterY + submergedHeight;
        topY = bottomY - objectSize;
      } else {
        bottomY = containerBottom;
        topY = bottomY - objectSize;
      }
      if (el.object) {
        el.object.setAttribute("x", String(200 - objectSize / 2));
        el.object.setAttribute("y", String(topY));
        el.object.setAttribute("width", String(objectSize));
        el.object.setAttribute("height", String(objectSize));
      }
      var text =
        "An object of density " + state.objectDensity.toFixed(0) + " kilograms per cubic metre in a fluid of density " +
        state.fluidDensity.toFixed(0) + " kilograms per cubic metre. The object " +
        (computed.floats ? "floats, " + (computed.submergedFraction * 100).toFixed(0) + " percent submerged." :
          "sinks, fully submerged, with a net downward force of " + computed.netForce.toFixed(2) + " newtons.");
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.barWeight || !el.barBuoyant) return;
      var maxVal = Math.max(1e-9, computed.weight, computed.maxBuoyantForce);
      var baseY = 150, maxBarH = 120;
      var weightH = (computed.weight / maxVal) * maxBarH;
      var buoyantH = (computed.maxBuoyantForce / maxVal) * maxBarH;
      el.barWeight.setAttribute("y", String(baseY - weightH));
      el.barWeight.setAttribute("height", String(weightH));
      el.barBuoyant.setAttribute("y", String(baseY - buoyantH));
      el.barBuoyant.setAttribute("height", String(buoyantH));
      if (el.barWeightLabel) {
        el.barWeightLabel.setAttribute("y", String(baseY - weightH - 6));
        el.barWeightLabel.textContent = computed.weight.toFixed(1) + " N";
      }
      if (el.barBuoyantLabel) {
        el.barBuoyantLabel.setAttribute("y", String(baseY - buoyantH - 6));
        el.barBuoyantLabel.textContent = computed.maxBuoyantForce.toFixed(1) + " N";
      }
      var graphText =
        "Comparing weight, " + computed.weight.toFixed(1) + " newtons, against the maximum possible " +
        "buoyant force if fully submerged, " + computed.maxBuoyantForce.toFixed(1) + " newtons. " +
        "The object floats only if the buoyant force can reach at least its weight.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueObjectDensity) el.valueObjectDensity.textContent = state.objectDensity.toFixed(0);
      if (el.valueFluidDensity) el.valueFluidDensity.textContent = state.fluidDensity.toFixed(0);
      if (el.valueVolume) el.valueVolume.textContent = state.volume.toFixed(4);
      if (el.valueWeight) el.valueWeight.textContent = computed.weight.toFixed(2);
      if (el.valueBuoyant) el.valueBuoyant.textContent = computed.buoyantForce.toFixed(2);
      if (el.valueNet) el.valueNet.textContent = computed.netForce.toFixed(2);
      if (el.valueVerdict) el.valueVerdict.textContent = computed.floats ? "Floats" : "Sinks";
      if (el.eqWeight) el.eqWeight.textContent = computed.weight.toFixed(2);
      if (el.eqBuoyant) el.eqBuoyant.textContent = computed.buoyantForce.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        objectDensityKgM3: state.objectDensity,
        fluidDensityKgM3: state.fluidDensity,
        volumeM3: state.volume,
        weightN: computed.weight,
        buoyantForceN: computed.buoyantForce,
        netForceN: computed.netForce,
        floats: computed.floats ? 1 : 0,
        running: false
      };
    }

    if (el.inputObjectDensity) {
      el.inputObjectDensity.addEventListener("input", function () { setObjectDensity(el.inputObjectDensity.value); });
      el.inputObjectDensity.addEventListener("change", function () { setObjectDensity(el.inputObjectDensity.value); });
    }
    if (el.inputFluidDensity) {
      el.inputFluidDensity.addEventListener("input", function () { setFluidDensity(el.inputFluidDensity.value); });
      el.inputFluidDensity.addEventListener("change", function () { setFluidDensity(el.inputFluidDensity.value); });
    }
    if (el.inputVolume) {
      el.inputVolume.addEventListener("input", function () { setVolume(el.inputVolume.value); });
      el.inputVolume.addEventListener("change", function () { setVolume(el.inputVolume.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setObjectDensity: setObjectDensity,
      setFluidDensity: setFluidDensity,
      setVolume: setVolume,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("buoyancy", createBuoyancySim);

  PhysicsLab.Buoyancy = {
    GRAVITY_MS2: GRAVITY_MS2,
    MIN_DENSITY_KG_M3: MIN_DENSITY_KG_M3,
    MAX_DENSITY_KG_M3: MAX_DENSITY_KG_M3,
    MIN_VOLUME_M3: MIN_VOLUME_M3,
    MAX_VOLUME_M3: MAX_VOLUME_M3,
    clampDensity: clampDensity,
    clampVolume: clampVolume,
    computeState: computeState
  };
})(window, document);
