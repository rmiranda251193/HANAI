/**
 * Energy on an Incline simulation.
 *
 * A block starts from rest at height h on a frictionless incline of angle
 * theta, slides down, then continues on frictionless flat ground:
 *
 * a = g*sin(theta)
 * t_end = sqrt(2h/g) / sin(theta), v_end = a*t_end = sqrt(2*g*h)
 * while on the ramp:  distance = (1/2)*a*t^2, heightDropped = distance*sin(theta), speed = a*t
 * once past the bottom: heightDropped = h, speed = v_end (constant)
 * KE = (1/2)*m*speed^2, PE = m*g*(h - heightDropped), total = KE + PE (constant)
 *
 * Always computed here, in code -- never fetched from a server and never
 * generated by AI. Mirrors apps/physics/simulations_energy_incline.py
 * exactly (same bounds, same formulas). This file owns its own physics,
 * SVG and controls; it shares only the run-loop/registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_HEIGHT_M = 1.0;
  var MAX_HEIGHT_M = 10.0;
  var MIN_ANGLE_DEG = 10.0;
  var MAX_ANGLE_DEG = 80.0;
  var MIN_MASS_KG = 0.5;
  var MAX_MASS_KG = 10.0;
  var GRAVITY_MS2 = 9.8;
  var MAX_TIME_S = 15.0;

  function clampHeight(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_HEIGHT_M, Math.min(MAX_HEIGHT_M, n));
  }
  function clampAngle(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_ANGLE_DEG, Math.min(MAX_ANGLE_DEG, n));
  }
  function clampMass(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_MASS_KG, Math.min(MAX_MASS_KG, n));
  }

  function computeState(height, angleDeg, mass, t) {
    height = clampHeight(height);
    angleDeg = clampAngle(angleDeg);
    mass = clampMass(mass);
    t = Math.max(0, Math.min(MAX_TIME_S, Number(t)));

    var theta = (angleDeg * Math.PI) / 180;
    var a = GRAVITY_MS2 * Math.sin(theta);
    var tEnd = Math.sqrt((2 * height) / GRAVITY_MS2) / Math.sin(theta);
    var vEnd = a * tEnd;

    var distance, heightDropped, speed;
    if (t < tEnd) {
      distance = 0.5 * a * t * t;
      heightDropped = distance * Math.sin(theta);
      speed = a * t;
    } else {
      var rampLength = height / Math.sin(theta);
      distance = rampLength + vEnd * (t - tEnd);
      heightDropped = height;
      speed = vEnd;
    }

    var ke = 0.5 * mass * speed * speed;
    var pe = mass * GRAVITY_MS2 * (height - heightDropped);
    var total = ke + pe;

    return {
      distance: distance, heightDropped: heightDropped, speed: speed,
      ke: ke, pe: pe, total: total, reachedBottom: t >= tEnd, tEnd: tEnd
    };
  }

  // Geometry constants for the SVG scene.
  var ORIGIN_X_PX = 30;
  var ORIGIN_Y_PX = 40;
  var TRACK_BOTTOM_Y_PX = 180;
  var TRACK_LENGTH_PX = 340;
  var STEP_S = 0.05;
  var REDUCED_MOTION_STOP_S = 6;

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createEnergyInclineSim(root, config, lab) {
    var state = {
      height: clampHeight(readNum(root, "height", 5)),
      angle: clampAngle(readNum(root, "angle", 30)),
      mass: clampMass(readNum(root, "mass", 2)),
      timeS: 0,
      distance: 0, heightDropped: 0, speed: 0,
      ke: 0, pe: 0, total: 0, reachedBottom: false, tEnd: 0
    };

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      cart: root.querySelector("[data-cart]"),
      ramp: root.querySelector("[data-ramp-line]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      valueHeight: root.querySelector("[data-value-height]"),
      valueAngle: root.querySelector("[data-value-angle]"),
      valueMass: root.querySelector("[data-value-mass]"),
      valueTime: root.querySelector("[data-value-time]"),
      valueSpeed: root.querySelector("[data-value-speed]"),
      valueKE: root.querySelector("[data-value-ke]"),
      valuePE: root.querySelector("[data-value-pe]"),
      valueTotal: root.querySelector("[data-value-total]"),
      outHeight: root.querySelector("[data-out-height]"),
      outAngle: root.querySelector("[data-out-angle]"),
      outMass: root.querySelector("[data-out-mass]"),
      inputHeight: root.querySelector("[data-input-height]"),
      inputAngle: root.querySelector("[data-input-angle]"),
      inputMass: root.querySelector("[data-input-mass]"),
      btnStart: root.querySelector("[data-action-start]"),
      btnPause: root.querySelector("[data-action-pause]"),
      btnReset: root.querySelector("[data-action-reset]"),
      btnStep: root.querySelector("[data-action-step]"),
      inputTime: root.querySelector("[data-input-time]"),
      outTime: root.querySelector("[data-out-time]"),
      motionNote: root.querySelector("[data-motion-note]")
    };

    var loop = lab.createRunLoop(tick, {});

    function recompute() {
      var c = computeState(state.height, state.angle, state.mass, state.timeS);
      state.distance = c.distance; state.heightDropped = c.heightDropped; state.speed = c.speed;
      state.ke = c.ke; state.pe = c.pe; state.total = c.total;
      state.reachedBottom = c.reachedBottom; state.tEnd = c.tEnd;
    }

    function setHeight(value) {
      state.height = clampHeight(value);
      if (el.inputHeight) el.inputHeight.value = String(state.height);
      if (el.outHeight) el.outHeight.textContent = String(state.height);
      setTime(0);
    }
    function setAngle(value) {
      state.angle = clampAngle(value);
      if (el.inputAngle) el.inputAngle.value = String(state.angle);
      if (el.outAngle) el.outAngle.textContent = String(state.angle);
      setTime(0);
    }
    function setMass(value) {
      state.mass = clampMass(value);
      if (el.inputMass) el.inputMass.value = String(state.mass);
      if (el.outMass) el.outMass.textContent = String(state.mass);
      setTime(0);
    }

    function start() { loop.start(); }
    function pause() { loop.stop(); }
    function reset() { loop.stop(); setTime(0); }

    function setTime(value) {
      loop.stop();
      var t = Number(value);
      if (!isFinite(t)) return;
      t = Math.max(0, Math.min(MAX_TIME_S, t));
      state.timeS = t;
      recompute();
      if (el.sceneStatus) {
        el.sceneStatus.textContent = state.reachedBottom
          ? "The block has reached the bottom and continues at a constant speed."
          : "";
      }
      render();
    }

    function stepForward() { setTime(state.timeS + STEP_S); }

    function tick(dt) {
      if (state.timeS >= MAX_TIME_S) {
        loop.stop();
        return;
      }
      state.timeS = Math.min(MAX_TIME_S, state.timeS + dt);
      recompute();
      if (state.timeS >= MAX_TIME_S) {
        loop.stop();
        if (el.sceneStatus) el.sceneStatus.textContent = "Reached the end of the simulated time window (15 s).";
      } else if (loop.reduced && state.timeS >= REDUCED_MOTION_STOP_S) {
        loop.stop();
      }
      render();
    }

    function renderScene() {
      // Fraction of the ramp covered (0..1), then continuing along flat ground.
      var theta = (state.angle * Math.PI) / 180;
      var rampLength = state.height / Math.sin(theta);
      var frac = Math.min(1, state.distance / rampLength);
      var cartX, cartY;
      if (frac < 1) {
        cartX = ORIGIN_X_PX + frac * TRACK_LENGTH_PX;
        cartY = ORIGIN_Y_PX + frac * (TRACK_BOTTOM_Y_PX - ORIGIN_Y_PX);
      } else {
        var extra = state.distance - rampLength;
        cartX = Math.min(ORIGIN_X_PX + TRACK_LENGTH_PX + extra * 10, 390);
        cartY = TRACK_BOTTOM_Y_PX;
      }
      if (el.cart) el.cart.setAttribute("transform", "translate(" + cartX.toFixed(1) + "," + cartY.toFixed(1) + ")");
      if (el.ramp) {
        el.ramp.setAttribute("x1", String(ORIGIN_X_PX));
        el.ramp.setAttribute("y1", String(ORIGIN_Y_PX));
        el.ramp.setAttribute("x2", String(ORIGIN_X_PX + TRACK_LENGTH_PX));
        el.ramp.setAttribute("y2", String(TRACK_BOTTOM_Y_PX));
      }
      var text =
        "A " + state.mass.toFixed(1) + " kilogram block starts at " + state.height.toFixed(1) +
        " metres up a " + state.angle.toFixed(0) + "-degree ramp. At " + state.timeS.toFixed(1) +
        " seconds it has travelled " + state.distance.toFixed(2) + " metres and is moving at " +
        state.speed.toFixed(2) + " metres per second.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function render() {
      if (el.valueHeight) el.valueHeight.textContent = String(state.height);
      if (el.valueAngle) el.valueAngle.textContent = String(state.angle);
      if (el.valueMass) el.valueMass.textContent = String(state.mass);
      if (el.valueTime) el.valueTime.textContent = state.timeS.toFixed(2);
      if (el.valueSpeed) el.valueSpeed.textContent = state.speed.toFixed(2);
      if (el.valueKE) el.valueKE.textContent = state.ke.toFixed(2);
      if (el.valuePE) el.valuePE.textContent = state.pe.toFixed(2);
      if (el.valueTotal) el.valueTotal.textContent = state.total.toFixed(2);
      if (el.inputTime && document.activeElement !== el.inputTime) {
        el.inputTime.value = String(Math.round(state.timeS * 10000) / 10000);
      }
      if (el.outTime) el.outTime.textContent = state.timeS.toFixed(1);
      renderScene();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        heightM: state.height,
        angleDeg: state.angle,
        massKg: state.mass,
        timeS: state.timeS,
        distanceM: state.distance,
        heightDroppedM: state.heightDropped,
        speedMs: state.speed,
        kineticEnergyJ: state.ke,
        potentialEnergyJ: state.pe,
        totalEnergyJ: state.total,
        running: loop.isRunning()
      };
    }

    if (el.inputHeight) {
      el.inputHeight.addEventListener("input", function () { setHeight(el.inputHeight.value); });
      el.inputHeight.addEventListener("change", function () { setHeight(el.inputHeight.value); });
    }
    if (el.inputAngle) {
      el.inputAngle.addEventListener("input", function () { setAngle(el.inputAngle.value); });
      el.inputAngle.addEventListener("change", function () { setAngle(el.inputAngle.value); });
    }
    if (el.inputMass) {
      el.inputMass.addEventListener("input", function () { setMass(el.inputMass.value); });
      el.inputMass.addEventListener("change", function () { setMass(el.inputMass.value); });
    }
    if (el.btnStart) el.btnStart.addEventListener("click", start);
    if (el.btnPause) el.btnPause.addEventListener("click", pause);
    if (el.btnReset) el.btnReset.addEventListener("click", reset);
    if (el.btnStep) el.btnStep.addEventListener("click", stepForward);
    if (el.inputTime) {
      el.inputTime.addEventListener("input", function () { setTime(el.inputTime.value); });
      el.inputTime.addEventListener("change", function () { setTime(el.inputTime.value); });
    }

    if (loop.reduced && el.motionNote) el.motionNote.hidden = false;

    reset();

    var api = {
      setHeight: setHeight,
      setAngle: setAngle,
      setMass: setMass,
      start: start,
      pause: pause,
      reset: reset,
      setTime: setTime,
      step: stepForward,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("energy_incline", createEnergyInclineSim);

  PhysicsLab.EnergyIncline = {
    MIN_HEIGHT_M: MIN_HEIGHT_M,
    MAX_HEIGHT_M: MAX_HEIGHT_M,
    MIN_ANGLE_DEG: MIN_ANGLE_DEG,
    MAX_ANGLE_DEG: MAX_ANGLE_DEG,
    MIN_MASS_KG: MIN_MASS_KG,
    MAX_MASS_KG: MAX_MASS_KG,
    GRAVITY_MS2: GRAVITY_MS2,
    MAX_TIME_S: MAX_TIME_S,
    clampHeight: clampHeight,
    clampAngle: clampAngle,
    clampMass: clampMass,
    computeState: computeState
  };
})(window, document);
