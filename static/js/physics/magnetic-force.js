/**
 * Magnetic Force on a Moving Charge simulation.
 *
 * omega = |q| B / m           (angular speed, aka the cyclotron frequency)
 * r = v / omega                (orbital radius)
 * T = 2*pi / omega             (orbital period -- independent of speed!)
 * F = |q| v B                  (force magnitude, always perpendicular to v)
 * theta(t) = direction * omega * t   (direction = +1 positive charge,
 *                                      -1 negative charge)
 * x(t) = r*cos(theta), y(t) = r*sin(theta)
 * speed stays exactly v at every instant -- the magnetic force changes
 * direction, never speed.
 *
 * Mirrors circular-motion.js closely (a charged particle in a field and a
 * string-swung object share the same x(t)/y(t)/speed shape; only how the
 * angular speed is derived differs, and here the ROTATION DIRECTION also
 * depends on the charge's sign). Always computed here, in code -- never
 * fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_magnetic_force.py exactly (same bounds, same
 * formulas). This file owns its own physics, SVG and controls; it shares
 * only the run-loop/registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_CHARGE_MAGNITUDE_C = 0.5;
  var MAX_CHARGE_MAGNITUDE_C = 3.0;
  var MIN_MASS_KG = 0.01;
  var MAX_MASS_KG = 2.0;
  var MIN_SPEED_M_S = 1.0;
  var MAX_SPEED_M_S = 50.0;
  var MIN_FIELD_T = 0.5;
  var MAX_FIELD_T = 5.0;
  var MAX_TIME_S = 20.0;

  function clampChargeMagnitude(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_CHARGE_MAGNITUDE_C, Math.min(MAX_CHARGE_MAGNITUDE_C, n));
  }
  function clampMass(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_MASS_KG, Math.min(MAX_MASS_KG, n));
  }
  function clampSpeed(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_SPEED_M_S, Math.min(MAX_SPEED_M_S, n));
  }
  function clampField(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_FIELD_T, Math.min(MAX_FIELD_T, n));
  }
  function clampPositiveCharge(value) {
    var n = Number(value);
    if (!isFinite(n)) return 1;
    return n >= 0.5 ? 1 : 0;
  }

  function computeState(chargeMagnitude, positiveCharge, mass, speed, field, t) {
    var q = clampChargeMagnitude(chargeMagnitude);
    var isPositive = clampPositiveCharge(positiveCharge) === 1;
    var m = clampMass(mass);
    var v = clampSpeed(speed);
    var b = clampField(field);
    t = Math.max(0, Math.min(MAX_TIME_S, Number(t)));

    var omega = (q * b) / m;
    var radius = v / omega;
    var period = (2 * Math.PI) / omega;
    var force = q * v * b;
    var direction = isPositive ? 1 : -1;

    var theta = direction * omega * t;
    var x = radius * Math.cos(theta);
    var y = radius * Math.sin(theta);
    var vx = -v * direction * Math.sin(theta);
    var vy = v * direction * Math.cos(theta);
    var currentSpeed = Math.sqrt(vx * vx + vy * vy);
    var angleDeg = ((theta * 180) / Math.PI) % 360;
    if (angleDeg < 0) angleDeg += 360;

    return {
      radius: radius,
      period: period,
      force: force,
      direction: direction,
      x: x,
      y: y,
      vx: vx,
      vy: vy,
      currentSpeed: currentSpeed,
      angleDeg: angleDeg
    };
  }

  var CENTER_X_PX = 200;
  var CENTER_Y_PX = 140;
  var USABLE_RADIUS_PX = 108;
  var STEP_S = 0.05;
  var REDUCED_MOTION_STOP_S = 6;

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }
  function round4(n) {
    return Math.round(n * 10000) / 10000;
  }

  function createMagneticForceSim(root, config, lab) {
    var state = {
      chargeMagnitude: clampChargeMagnitude(readNum(root, "charge-magnitude", 1)),
      positiveCharge: clampPositiveCharge(readNum(root, "positive-charge", 1)),
      mass: clampMass(readNum(root, "mass", 0.1)),
      speed: clampSpeed(readNum(root, "speed", 10)),
      field: clampField(readNum(root, "field", 2)),
      timeS: 0,
      x: 0, y: 0, radius: 0, period: 0, force: 0, currentSpeed: 0, angleDeg: 0,
      scale: 10
    };

    var trace = [];
    var maxAbsY = 1;

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      marker: root.querySelector("[data-cart]"),
      orbit: root.querySelector("[data-orbit-circle]"),
      radiusLine: root.querySelector("[data-radius-line]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      trace: root.querySelector("[data-lab-trace]"),
      valueRadius: root.querySelector("[data-value-radius]"),
      valuePeriod: root.querySelector("[data-value-period]"),
      valueTime: root.querySelector("[data-value-time]"),
      valueForce: root.querySelector("[data-value-force]"),
      valueSpeed: root.querySelector("[data-value-speed]"),
      eqRadius: root.querySelector("[data-eq-radius]"),
      eqPeriod: root.querySelector("[data-eq-period]"),
      outCharge: root.querySelector("[data-out-charge-magnitude]"),
      outMass: root.querySelector("[data-out-mass]"),
      outSpeed: root.querySelector("[data-out-speed]"),
      outField: root.querySelector("[data-out-field]"),
      inputCharge: root.querySelector("[data-input-charge-magnitude]"),
      inputSign: root.querySelectorAll("[data-input-positive-charge]"),
      inputMass: root.querySelector("[data-input-mass]"),
      inputSpeed: root.querySelector("[data-input-speed]"),
      inputField: root.querySelector("[data-input-field]"),
      btnStart: root.querySelector("[data-action-start]"),
      btnPause: root.querySelector("[data-action-pause]"),
      btnReset: root.querySelector("[data-action-reset]"),
      btnStep: root.querySelector("[data-action-step]"),
      inputTime: root.querySelector("[data-input-time]"),
      outTime: root.querySelector("[data-out-time]"),
      motionNote: root.querySelector("[data-motion-note]")
    };

    var loop = lab.createRunLoop(tick, {});

    function updateScale() {
      state.scale = USABLE_RADIUS_PX / Math.max(0.01, state.radius);
    }
    function screenX(xM) { return CENTER_X_PX + xM * state.scale; }
    function screenY(yM) { return CENTER_Y_PX - yM * state.scale; }

    function recordTrace() {
      trace.push([round4(state.timeS), round4(state.y)]);
      maxAbsY = Math.max(maxAbsY, Math.abs(state.y));
      if (trace.length > 2000) trace.shift();
    }

    function applyComputed(computed) {
      state.x = computed.x;
      state.y = computed.y;
      state.radius = computed.radius;
      state.period = computed.period;
      state.force = computed.force;
      state.currentSpeed = computed.currentSpeed;
      state.angleDeg = computed.angleDeg;
    }

    function setChargeMagnitude(value) {
      state.chargeMagnitude = clampChargeMagnitude(value);
      if (el.inputCharge) el.inputCharge.value = String(state.chargeMagnitude);
      if (el.outCharge) el.outCharge.textContent = String(state.chargeMagnitude);
      setTime(0);
    }
    function setPositiveCharge(value) {
      state.positiveCharge = clampPositiveCharge(value);
      for (var i = 0; i < el.inputSign.length; i++) {
        el.inputSign[i].checked = (el.inputSign[i].value === (state.positiveCharge ? "1" : "0"));
      }
      setTime(0);
    }
    function setMass(value) {
      state.mass = clampMass(value);
      if (el.inputMass) el.inputMass.value = String(state.mass);
      if (el.outMass) el.outMass.textContent = String(state.mass);
      setTime(0);
    }
    function setSpeed(value) {
      state.speed = clampSpeed(value);
      if (el.inputSpeed) el.inputSpeed.value = String(state.speed);
      if (el.outSpeed) el.outSpeed.textContent = String(state.speed);
      updateScale();
      setTime(0);
    }
    function setField(value) {
      state.field = clampField(value);
      if (el.inputField) el.inputField.value = String(state.field);
      if (el.outField) el.outField.textContent = String(state.field);
      setTime(0);
    }

    function start() { loop.start(); }
    function pause() { loop.stop(); }
    function reset() { loop.stop(); setTime(0); }

    function rebuildTrace(upToT) {
      trace = [];
      maxAbsY = Math.max(1, state.radius);
      var sampleDt = Math.max(upToT / 60, 0.01);
      for (var t = 0; t < upToT - 1e-9; t += sampleDt) {
        var c = computeState(state.chargeMagnitude, state.positiveCharge, state.mass, state.speed, state.field, t);
        trace.push([round4(t), round4(c.y)]);
      }
      trace.push([round4(upToT), round4(state.y)]);
    }

    function setTime(value) {
      loop.stop();
      var t = Number(value);
      if (!isFinite(t)) return;
      t = Math.max(0, Math.min(MAX_TIME_S, t));
      var computed = computeState(state.chargeMagnitude, state.positiveCharge, state.mass, state.speed, state.field, t);
      state.timeS = t;
      applyComputed(computed);
      updateScale();
      rebuildTrace(t);
      if (el.sceneStatus) el.sceneStatus.textContent = "";
      render();
    }

    function stepForward() { setTime(state.timeS + STEP_S); }

    function tick(dt) {
      if (state.timeS >= MAX_TIME_S) {
        loop.stop();
        if (el.sceneStatus) {
          el.sceneStatus.textContent = "Reached the end of the simulated time window (20 s).";
        }
        return;
      }
      var nextT = Math.min(MAX_TIME_S, state.timeS + dt);
      var computed = computeState(state.chargeMagnitude, state.positiveCharge, state.mass, state.speed, state.field, nextT);
      state.timeS = nextT;
      applyComputed(computed);
      recordTrace();
      if (loop.reduced && state.timeS >= REDUCED_MOTION_STOP_S) loop.stop();
      render();
    }

    function renderScene() {
      if (el.marker) {
        el.marker.setAttribute(
          "transform",
          "translate(" + screenX(state.x).toFixed(1) + "," + screenY(state.y).toFixed(1) + ")"
        );
        el.marker.setAttribute("fill", state.positiveCharge ? "#e0575b" : "#4fa8e0");
      }
      if (el.orbit) {
        el.orbit.setAttribute("cx", String(CENTER_X_PX));
        el.orbit.setAttribute("cy", String(CENTER_Y_PX));
        el.orbit.setAttribute("r", String(state.radius * state.scale));
      }
      if (el.radiusLine) {
        el.radiusLine.setAttribute("x1", String(CENTER_X_PX));
        el.radiusLine.setAttribute("y1", String(CENTER_Y_PX));
        el.radiusLine.setAttribute("x2", screenX(state.x).toFixed(1));
        el.radiusLine.setAttribute("y2", screenY(state.y).toFixed(1));
      }
      var text =
        "A " + (state.positiveCharge ? "positive" : "negative") + " charge moving in a circle of radius " +
        state.radius.toFixed(2) + " metres, completing one orbit every " + state.period.toFixed(2) +
        " seconds. At " + state.timeS.toFixed(2) + " seconds its speed is still " +
        state.currentSpeed.toFixed(1) + " metres per second -- unchanged.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.trace) return;
      var w = 348, h = 156, left = 40, top = 10, bottom = 6;
      var tMin = trace.length ? trace[0][0] : 0;
      var tMax = Math.max(tMin + 1, state.timeS);
      var yMax = Math.max(1, maxAbsY);
      var points = [];
      for (var i = 0; i < trace.length; i++) {
        var px = left + ((trace[i][0] - tMin) / (tMax - tMin)) * (w - left - 12);
        var py = h - bottom - ((trace[i][1] + yMax) / (2 * yMax)) * (h - top - bottom);
        points.push(px.toFixed(1) + "," + py.toFixed(1));
      }
      el.trace.setAttribute("points", points.join(" "));
      var graphText =
        "y-position vs time. At " + state.timeS.toFixed(2) + " seconds the y-position is " +
        state.y.toFixed(2) + " metres.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueRadius) el.valueRadius.textContent = state.radius.toFixed(2);
      if (el.valuePeriod) el.valuePeriod.textContent = state.period.toFixed(2);
      if (el.valueTime) el.valueTime.textContent = state.timeS.toFixed(2);
      if (el.valueForce) el.valueForce.textContent = state.force.toFixed(2);
      if (el.valueSpeed) el.valueSpeed.textContent = state.currentSpeed.toFixed(1);
      if (el.eqRadius) el.eqRadius.textContent = state.radius.toFixed(2);
      if (el.eqPeriod) el.eqPeriod.textContent = state.period.toFixed(2);
      if (el.inputTime && document.activeElement !== el.inputTime) {
        el.inputTime.value = String(round4(state.timeS));
      }
      if (el.outTime) el.outTime.textContent = state.timeS.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        chargeMagnitudeC: state.chargeMagnitude,
        positiveCharge: state.positiveCharge,
        massKg: state.mass,
        speedMs: state.speed,
        fieldT: state.field,
        timeS: state.timeS,
        radiusM: state.radius,
        periodS: state.period,
        forceN: state.force,
        positionXM: state.x,
        positionYM: state.y,
        running: loop.isRunning()
      };
    }

    if (el.inputCharge) {
      el.inputCharge.addEventListener("input", function () { setChargeMagnitude(el.inputCharge.value); });
      el.inputCharge.addEventListener("change", function () { setChargeMagnitude(el.inputCharge.value); });
    }
    for (var s = 0; s < el.inputSign.length; s++) {
      (function (radio) {
        radio.addEventListener("change", function () { if (radio.checked) setPositiveCharge(radio.value); });
      })(el.inputSign[s]);
    }
    if (el.inputMass) {
      el.inputMass.addEventListener("input", function () { setMass(el.inputMass.value); });
      el.inputMass.addEventListener("change", function () { setMass(el.inputMass.value); });
    }
    if (el.inputSpeed) {
      el.inputSpeed.addEventListener("input", function () { setSpeed(el.inputSpeed.value); });
      el.inputSpeed.addEventListener("change", function () { setSpeed(el.inputSpeed.value); });
    }
    if (el.inputField) {
      el.inputField.addEventListener("input", function () { setField(el.inputField.value); });
      el.inputField.addEventListener("change", function () { setField(el.inputField.value); });
    }
    if (el.btnStart) el.btnStart.addEventListener("click", start);
    if (el.btnPause) el.btnPause.addEventListener("click", pause);
    if (el.btnReset) el.btnReset.addEventListener("click", reset);
    if (el.btnStep) el.btnStep.addEventListener("click", stepForward);
    if (el.inputTime) {
      el.inputTime.addEventListener("input", function () { setTime(el.inputTime.value); });
      el.inputTime.addEventListener("change", function () { setTime(el.inputTime.value); });
    }

    if (loop.reduced && el.motionNote) el.motionNote.hidden = false;

    applyComputed(computeState(state.chargeMagnitude, state.positiveCharge, state.mass, state.speed, state.field, 0));
    updateScale();
    reset();

    var api = {
      setChargeMagnitude: setChargeMagnitude,
      setPositiveCharge: setPositiveCharge,
      setMass: setMass,
      setSpeed: setSpeed,
      setField: setField,
      start: start,
      pause: pause,
      reset: reset,
      setTime: setTime,
      step: stepForward,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("magnetic_force", createMagneticForceSim);

  PhysicsLab.MagneticForce = {
    MIN_CHARGE_MAGNITUDE_C: MIN_CHARGE_MAGNITUDE_C,
    MAX_CHARGE_MAGNITUDE_C: MAX_CHARGE_MAGNITUDE_C,
    MIN_MASS_KG: MIN_MASS_KG,
    MAX_MASS_KG: MAX_MASS_KG,
    MIN_SPEED_M_S: MIN_SPEED_M_S,
    MAX_SPEED_M_S: MAX_SPEED_M_S,
    MIN_FIELD_T: MIN_FIELD_T,
    MAX_FIELD_T: MAX_FIELD_T,
    MAX_TIME_S: MAX_TIME_S,
    clampChargeMagnitude: clampChargeMagnitude,
    clampMass: clampMass,
    clampSpeed: clampSpeed,
    clampField: clampField,
    clampPositiveCharge: clampPositiveCharge,
    computeState: computeState
  };
})(window, document);
