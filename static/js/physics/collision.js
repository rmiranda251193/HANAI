/**
 * Momentum and Collisions simulation.
 *
 * Cart 1 starts at x=0 moving right at v1 (always positive); cart 2 starts
 * at rest at a fixed separation. Before the collision, both move (or sit)
 * at constant velocity. At the collision time t_c = SEPARATION_M / v1,
 * momentum is conserved and either kinetic energy is also conserved
 * (elastic) or the carts stick together (perfectly inelastic):
 *
 * elastic:            v1' = ((m1-m2)/(m1+m2))*v1, v2' = (2*m1/(m1+m2))*v1
 * perfectly inelastic: v1' = v2' = (m1*v1)/(m1+m2)
 *
 * Always computed here, in code -- never fetched from a server and never
 * generated by AI. Mirrors apps/physics/simulations_collision.py exactly
 * (same bounds, same formulas). This file owns its own physics, SVG and
 * controls; it shares only the run-loop/registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_MASS_KG = 0.5;
  var MAX_MASS_KG = 10.0;
  var MIN_V0_MS = 0.5;
  var MAX_V0_MS = 10.0;
  var SEPARATION_M = 8.0;
  var MAX_TIME_S = 20.0;

  function clampMass(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_MASS_KG, Math.min(MAX_MASS_KG, n));
  }
  function clampV0(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_V0_MS, Math.min(MAX_V0_MS, n));
  }
  function clampElastic(value) {
    var n = Number(value);
    if (!isFinite(n)) return 1;
    return n >= 0.5 ? 1 : 0;
  }

  function computeState(mass1, mass2, v0, elastic, t) {
    mass1 = clampMass(mass1);
    mass2 = clampMass(mass2);
    v0 = clampV0(v0);
    var isElastic = clampElastic(elastic) === 1;
    t = Math.max(0, Math.min(MAX_TIME_S, Number(t)));

    var tc = SEPARATION_M / v0;
    var x1, x2, v1, v2, hasCollided;
    if (t < tc) {
      x1 = v0 * t;
      x2 = SEPARATION_M;
      v1 = v0;
      v2 = 0;
      hasCollided = false;
    } else {
      if (isElastic) {
        v1 = ((mass1 - mass2) / (mass1 + mass2)) * v0;
        v2 = (2 * mass1 / (mass1 + mass2)) * v0;
      } else {
        v1 = v2 = (mass1 * v0) / (mass1 + mass2);
      }
      var dt = t - tc;
      x1 = SEPARATION_M + v1 * dt;
      x2 = SEPARATION_M + v2 * dt;
      hasCollided = true;
    }
    var momentum = mass1 * v1 + mass2 * v2;
    var ke = 0.5 * mass1 * v1 * v1 + 0.5 * mass2 * v2 * v2;
    return {
      x1: x1, x2: x2, v1: v1, v2: v2,
      hasCollided: hasCollided, collisionTime: tc,
      momentum: momentum, ke: ke
    };
  }

  // Geometry constants for the SVG scene.
  var ORIGIN_X_PX = 20;
  var TRACK_Y_PX = 140;
  var PX_PER_METRE = 30;
  var STEP_S = 0.05;
  var REDUCED_MOTION_STOP_S = 6;

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createCollisionSim(root, config, lab) {
    var state = {
      mass1: clampMass(readNum(root, "mass1", 2)),
      mass2: clampMass(readNum(root, "mass2", 2)),
      v0: clampV0(readNum(root, "v0", 4)),
      elastic: clampElastic(readNum(root, "elastic", 1)),
      timeS: 0,
      x1: 0, x2: SEPARATION_M, v1: 0, v2: 0,
      hasCollided: false, collisionTime: SEPARATION_M / 4,
      momentum: 0, ke: 0
    };

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      cart1: root.querySelector("[data-cart1]"),
      cart2: root.querySelector("[data-cart2]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      valueMass1: root.querySelector("[data-value-mass1]"),
      valueMass2: root.querySelector("[data-value-mass2]"),
      valueV0: root.querySelector("[data-value-v0]"),
      valueTime: root.querySelector("[data-value-time]"),
      valueV1: root.querySelector("[data-value-v1]"),
      valueV2: root.querySelector("[data-value-v2]"),
      valueMomentum: root.querySelector("[data-value-momentum]"),
      valueKE: root.querySelector("[data-value-ke]"),
      outMass1: root.querySelector("[data-out-mass1]"),
      outMass2: root.querySelector("[data-out-mass2]"),
      outV0: root.querySelector("[data-out-v0]"),
      inputMass1: root.querySelector("[data-input-mass1]"),
      inputMass2: root.querySelector("[data-input-mass2]"),
      inputV0: root.querySelector("[data-input-v0]"),
      radioElastic: root.querySelectorAll("[data-input-elastic]"),
      btnStart: root.querySelector("[data-action-start]"),
      btnPause: root.querySelector("[data-action-pause]"),
      btnReset: root.querySelector("[data-action-reset]"),
      btnStep: root.querySelector("[data-action-step]"),
      inputTime: root.querySelector("[data-input-time]"),
      outTime: root.querySelector("[data-out-time]"),
      motionNote: root.querySelector("[data-motion-note]")
    };

    var loop = lab.createRunLoop(tick, {});

    function screenX(xM) {
      return ORIGIN_X_PX + xM * PX_PER_METRE;
    }

    function recompute() {
      var c = computeState(state.mass1, state.mass2, state.v0, state.elastic, state.timeS);
      state.x1 = c.x1; state.x2 = c.x2; state.v1 = c.v1; state.v2 = c.v2;
      state.hasCollided = c.hasCollided; state.collisionTime = c.collisionTime;
      state.momentum = c.momentum; state.ke = c.ke;
    }

    function setMass1(value) {
      state.mass1 = clampMass(value);
      if (el.inputMass1) el.inputMass1.value = String(state.mass1);
      if (el.outMass1) el.outMass1.textContent = String(state.mass1);
      setTime(0);
    }
    function setMass2(value) {
      state.mass2 = clampMass(value);
      if (el.inputMass2) el.inputMass2.value = String(state.mass2);
      if (el.outMass2) el.outMass2.textContent = String(state.mass2);
      setTime(0);
    }
    function setV0(value) {
      state.v0 = clampV0(value);
      if (el.inputV0) el.inputV0.value = String(state.v0);
      if (el.outV0) el.outV0.textContent = String(state.v0);
      setTime(0);
    }
    function setElastic(value) {
      state.elastic = clampElastic(value);
      setTime(0);
    }

    function start() {
      loop.start();
    }
    function pause() {
      loop.stop();
    }
    function reset() {
      loop.stop();
      setTime(0);
    }

    function setTime(value) {
      loop.stop();
      var t = Number(value);
      if (!isFinite(t)) return;
      t = Math.max(0, Math.min(MAX_TIME_S, t));
      state.timeS = t;
      recompute();
      if (el.sceneStatus) {
        el.sceneStatus.textContent = state.hasCollided ? "The carts have collided." : "";
      }
      render();
    }

    function stepForward() {
      setTime(state.timeS + STEP_S);
    }

    function tick(dt) {
      if (state.timeS >= MAX_TIME_S) {
        loop.stop();
        return;
      }
      var nextT = Math.min(MAX_TIME_S, state.timeS + dt);
      state.timeS = nextT;
      recompute();
      if (state.timeS >= MAX_TIME_S) {
        loop.stop();
        if (el.sceneStatus) el.sceneStatus.textContent = "Reached the end of the simulated time window (20 s).";
      } else if (loop.reduced && state.timeS >= REDUCED_MOTION_STOP_S) {
        loop.stop();
      }
      render();
    }

    function renderScene() {
      if (el.cart1) el.cart1.setAttribute("transform", "translate(" + screenX(state.x1).toFixed(1) + "," + TRACK_Y_PX + ")");
      if (el.cart2) el.cart2.setAttribute("transform", "translate(" + screenX(state.x2).toFixed(1) + "," + TRACK_Y_PX + ")");
      var text =
        "Cart 1 (" + state.mass1.toFixed(1) + " kg) approaches cart 2 (" + state.mass2.toFixed(1) +
        " kg, at rest) at " + state.v0.toFixed(1) + " metres per second. At " + state.timeS.toFixed(1) +
        " seconds, cart 1 is at " + state.x1.toFixed(2) + " m moving at " + state.v1.toFixed(2) +
        " m/s, and cart 2 is at " + state.x2.toFixed(2) + " m moving at " + state.v2.toFixed(2) + " m/s.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function render() {
      if (el.valueMass1) el.valueMass1.textContent = String(state.mass1);
      if (el.valueMass2) el.valueMass2.textContent = String(state.mass2);
      if (el.valueV0) el.valueV0.textContent = String(state.v0);
      if (el.valueTime) el.valueTime.textContent = state.timeS.toFixed(2);
      if (el.valueV1) el.valueV1.textContent = state.v1.toFixed(2);
      if (el.valueV2) el.valueV2.textContent = state.v2.toFixed(2);
      if (el.valueMomentum) el.valueMomentum.textContent = state.momentum.toFixed(2);
      if (el.valueKE) el.valueKE.textContent = state.ke.toFixed(2);
      if (el.inputTime && document.activeElement !== el.inputTime) {
        el.inputTime.value = String(Math.round(state.timeS * 10000) / 10000);
      }
      if (el.outTime) el.outTime.textContent = state.timeS.toFixed(1);
      renderScene();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        mass1Kg: state.mass1,
        mass2Kg: state.mass2,
        initialVelocityMs: state.v0,
        elastic: state.elastic,
        timeS: state.timeS,
        position1M: state.x1,
        position2M: state.x2,
        velocity1Ms: state.v1,
        velocity2Ms: state.v2,
        hasCollided: state.hasCollided,
        momentumTotalKgMs: state.momentum,
        kineticEnergyTotalJ: state.ke,
        running: loop.isRunning()
      };
    }

    if (el.inputMass1) {
      el.inputMass1.addEventListener("input", function () { setMass1(el.inputMass1.value); });
      el.inputMass1.addEventListener("change", function () { setMass1(el.inputMass1.value); });
    }
    if (el.inputMass2) {
      el.inputMass2.addEventListener("input", function () { setMass2(el.inputMass2.value); });
      el.inputMass2.addEventListener("change", function () { setMass2(el.inputMass2.value); });
    }
    if (el.inputV0) {
      el.inputV0.addEventListener("input", function () { setV0(el.inputV0.value); });
      el.inputV0.addEventListener("change", function () { setV0(el.inputV0.value); });
    }
    if (el.radioElastic && el.radioElastic.length) {
      for (var i = 0; i < el.radioElastic.length; i++) {
        el.radioElastic[i].addEventListener("change", function (ev) {
          if (ev.target.checked) setElastic(ev.target.value);
        });
      }
    }
    if (el.btnStart) el.btnStart.addEventListener("click", start);
    if (el.btnPause) el.btnPause.addEventListener("click", pause);
    if (el.btnReset) el.btnReset.addEventListener("click", reset);
    if (el.btnStep) el.btnStep.addEventListener("click", stepForward);
    if (el.inputTime) {
      el.inputTime.addEventListener("input", function () { setTime(el.inputTime.value); });
      el.inputTime.addEventListener("change", function () { setTime(el.inputTime.value); });
    }

    if (loop.reduced && el.motionNote) el.motionNote.hidden = false;

    reset();

    var api = {
      setMass1: setMass1,
      setMass2: setMass2,
      setInitialVelocity: setV0,
      setElastic: setElastic,
      start: start,
      pause: pause,
      reset: reset,
      setTime: setTime,
      step: stepForward,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("momentum_collision", createCollisionSim);

  PhysicsLab.Collision = {
    MIN_MASS_KG: MIN_MASS_KG,
    MAX_MASS_KG: MAX_MASS_KG,
    MIN_V0_MS: MIN_V0_MS,
    MAX_V0_MS: MAX_V0_MS,
    SEPARATION_M: SEPARATION_M,
    MAX_TIME_S: MAX_TIME_S,
    clampMass: clampMass,
    clampV0: clampV0,
    clampElastic: clampElastic,
    computeState: computeState
  };
})(window, document);
