/**
 * Electromagnetic Induction (Faraday's Law) simulation.
 *
 * deltaFlux = area * (fieldFinal - fieldInitial)
 * EMF = turns * |deltaFlux| / timeInterval
 *
 * The EMF reported is a magnitude (what a voltmeter reads); the induced
 * current's DIRECTION is Lenz's law's domain, represented here only as
 * fluxIncreasing (growing vs shrinking field), not a signed EMF -- a
 * growing and an equally-fast shrinking field give the same EMF magnitude
 * with opposite qualitative directions. Like circuits.js/coulombs-law.js/
 * buoyancy.js/refraction.js/calorimetry.js/ideal-gas-law.js/
 * doppler-effect.js/time-dilation.js/photoelectric-effect.js, there is no
 * time axis (in the animation sense) and no run loop: values are
 * recomputed live on every control change. Always computed here, in code
 * -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_electromagnetic_induction.py exactly (same
 * bounds, same formula). This file owns its own physics, SVG and
 * controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_TURNS = 1.0;
  var MAX_TURNS = 500.0;
  var MIN_AREA_M2 = 0.001;
  var MAX_AREA_M2 = 1.0;
  var MIN_FIELD_T = 0.0;
  var MAX_FIELD_T = 2.0;
  var MIN_TIME_INTERVAL_S = 0.01;
  var MAX_TIME_INTERVAL_S = 10.0;

  function clampTurns(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_TURNS, Math.min(MAX_TURNS, n));
  }
  function clampArea(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_AREA_M2, Math.min(MAX_AREA_M2, n));
  }
  function clampField(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_FIELD_T, Math.min(MAX_FIELD_T, n));
  }
  function clampTimeInterval(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_TIME_INTERVAL_S, Math.min(MAX_TIME_INTERVAL_S, n));
  }

  function computeState(turns, areaM2, fieldInitial, fieldFinal, timeInterval) {
    var n = clampTurns(turns);
    var a = clampArea(areaM2);
    var b1 = clampField(fieldInitial);
    var b2 = clampField(fieldFinal);
    var dt = clampTimeInterval(timeInterval);

    var deltaFlux = a * (b2 - b1);
    var emf = (n * Math.abs(deltaFlux)) / dt;
    var fluxIncreasing = b2 > b1;

    return {
      turns: n,
      area: a,
      fieldInitial: b1,
      fieldFinal: b2,
      timeInterval: dt,
      deltaFlux: deltaFlux,
      emf: emf,
      fluxIncreasing: fluxIncreasing
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createElectromagneticInductionSim(root, config, lab) {
    var state = {
      turns: clampTurns(readNum(root, "turns", 100)),
      area: clampArea(readNum(root, "area", 0.05)),
      fieldInitial: clampField(readNum(root, "field-initial", 0)),
      fieldFinal: clampField(readNum(root, "field-final", 1)),
      timeInterval: clampTimeInterval(readNum(root, "time-interval", 0.5))
    };
    var computed = computeState(
      state.turns, state.area, state.fieldInitial, state.fieldFinal, state.timeInterval
    );

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      currentArrowCw: root.querySelector("[data-current-cw]"),
      currentArrowCcw: root.querySelector("[data-current-ccw]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueTurns: root.querySelector("[data-value-turns]"),
      valueArea: root.querySelector("[data-value-area]"),
      valueFieldInitial: root.querySelector("[data-value-field-initial]"),
      valueFieldFinal: root.querySelector("[data-value-field-final]"),
      valueInterval: root.querySelector("[data-value-interval]"),
      valueEmf: root.querySelector("[data-value-emf]"),
      valueDirection: root.querySelector("[data-value-direction]"),
      eqEmf: root.querySelector("[data-eq-emf]"),
      outTurns: root.querySelector("[data-out-turns]"),
      outArea: root.querySelector("[data-out-area]"),
      outFieldInitial: root.querySelector("[data-out-field-initial]"),
      outFieldFinal: root.querySelector("[data-out-field-final]"),
      outInterval: root.querySelector("[data-out-interval]"),
      inputTurns: root.querySelector("[data-input-turns]"),
      inputArea: root.querySelector("[data-input-area]"),
      inputFieldInitial: root.querySelector("[data-input-field-initial]"),
      inputFieldFinal: root.querySelector("[data-input-field-final]"),
      inputInterval: root.querySelector("[data-input-interval]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(
        state.turns, state.area, state.fieldInitial, state.fieldFinal, state.timeInterval
      );
    }

    function setTurns(value) {
      state.turns = clampTurns(value);
      if (el.inputTurns) el.inputTurns.value = String(state.turns);
      if (el.outTurns) el.outTurns.textContent = String(state.turns);
      recompute();
      render();
    }
    function setArea(value) {
      state.area = clampArea(value);
      if (el.inputArea) el.inputArea.value = String(state.area);
      if (el.outArea) el.outArea.textContent = String(state.area);
      recompute();
      render();
    }
    function setFieldInitial(value) {
      state.fieldInitial = clampField(value);
      if (el.inputFieldInitial) el.inputFieldInitial.value = String(state.fieldInitial);
      if (el.outFieldInitial) el.outFieldInitial.textContent = String(state.fieldInitial);
      recompute();
      render();
    }
    function setFieldFinal(value) {
      state.fieldFinal = clampField(value);
      if (el.inputFieldFinal) el.inputFieldFinal.value = String(state.fieldFinal);
      if (el.outFieldFinal) el.outFieldFinal.textContent = String(state.fieldFinal);
      recompute();
      render();
    }
    function setTimeInterval(value) {
      state.timeInterval = clampTimeInterval(value);
      if (el.inputInterval) el.inputInterval.value = String(state.timeInterval);
      if (el.outInterval) el.outInterval.textContent = String(state.timeInterval);
      recompute();
      render();
    }
    function reset() {
      setTurns(100);
      setArea(0.05);
      setFieldInitial(0);
      setFieldFinal(1);
      setTimeInterval(0.5);
    }

    function renderScene() {
      var noChange = Math.abs(state.fieldFinal - state.fieldInitial) < 1e-9;
      if (el.currentArrowCw) {
        el.currentArrowCw.setAttribute("visibility", (!noChange && computed.fluxIncreasing) ? "visible" : "hidden");
      }
      if (el.currentArrowCcw) {
        el.currentArrowCcw.setAttribute("visibility", (!noChange && !computed.fluxIncreasing) ? "visible" : "hidden");
      }
      var text = noChange
        ? "The field does not change, so there is no induced EMF."
        : "The field goes from " + state.fieldInitial.toFixed(2) + " to " + state.fieldFinal.toFixed(2) +
          " tesla over " + state.timeInterval.toFixed(2) + " seconds, inducing " +
          computed.emf.toFixed(2) + " volts, with the flux " + (computed.fluxIncreasing ? "increasing" : "decreasing") + ".";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var samples = 40;
      var maxEmf = 1e-9;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var dt = MIN_TIME_INTERVAL_S + ((MAX_TIME_INTERVAL_S - MIN_TIME_INTERVAL_S) * i) / samples;
        var c = computeState(state.turns, state.area, state.fieldInitial, state.fieldFinal, dt);
        points.push([dt, c.emf]);
        if (c.emf > maxEmf) maxEmf = c.emf;
      }
      var path = points.map(function (p) {
        var px = left + ((p[0] - MIN_TIME_INTERVAL_S) / (MAX_TIME_INTERVAL_S - MIN_TIME_INTERVAL_S)) * plotW;
        var py = top + plotH - (p[1] / maxEmf) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        var mx = left + ((state.timeInterval - MIN_TIME_INTERVAL_S) / (MAX_TIME_INTERVAL_S - MIN_TIME_INTERVAL_S)) * plotW;
        var my = top + plotH - (computed.emf / maxEmf) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "Induced EMF versus the time interval over which the field changes, for this coil and field range. " +
        "A slower change induces a smaller EMF.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueTurns) el.valueTurns.textContent = state.turns.toFixed(0);
      if (el.valueArea) el.valueArea.textContent = state.area.toFixed(3);
      if (el.valueFieldInitial) el.valueFieldInitial.textContent = state.fieldInitial.toFixed(2);
      if (el.valueFieldFinal) el.valueFieldFinal.textContent = state.fieldFinal.toFixed(2);
      if (el.valueInterval) el.valueInterval.textContent = state.timeInterval.toFixed(2);
      if (el.valueEmf) el.valueEmf.textContent = computed.emf.toFixed(2);
      if (el.valueDirection) {
        el.valueDirection.textContent = computed.fluxIncreasing ? "Flux increasing" : "Flux decreasing";
      }
      if (el.eqEmf) el.eqEmf.textContent = computed.emf.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        turns: state.turns,
        areaM2: state.area,
        fieldInitialT: state.fieldInitial,
        fieldFinalT: state.fieldFinal,
        timeIntervalS: state.timeInterval,
        deltaFluxWb: computed.deltaFlux,
        emfV: computed.emf,
        running: false
      };
    }

    if (el.inputTurns) {
      el.inputTurns.addEventListener("input", function () { setTurns(el.inputTurns.value); });
      el.inputTurns.addEventListener("change", function () { setTurns(el.inputTurns.value); });
    }
    if (el.inputArea) {
      el.inputArea.addEventListener("input", function () { setArea(el.inputArea.value); });
      el.inputArea.addEventListener("change", function () { setArea(el.inputArea.value); });
    }
    if (el.inputFieldInitial) {
      el.inputFieldInitial.addEventListener("input", function () { setFieldInitial(el.inputFieldInitial.value); });
      el.inputFieldInitial.addEventListener("change", function () { setFieldInitial(el.inputFieldInitial.value); });
    }
    if (el.inputFieldFinal) {
      el.inputFieldFinal.addEventListener("input", function () { setFieldFinal(el.inputFieldFinal.value); });
      el.inputFieldFinal.addEventListener("change", function () { setFieldFinal(el.inputFieldFinal.value); });
    }
    if (el.inputInterval) {
      el.inputInterval.addEventListener("input", function () { setTimeInterval(el.inputInterval.value); });
      el.inputInterval.addEventListener("change", function () { setTimeInterval(el.inputInterval.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setTurns: setTurns,
      setArea: setArea,
      setFieldInitial: setFieldInitial,
      setFieldFinal: setFieldFinal,
      setTimeInterval: setTimeInterval,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("electromagnetic_induction", createElectromagneticInductionSim);

  PhysicsLab.ElectromagneticInduction = {
    MIN_TURNS: MIN_TURNS,
    MAX_TURNS: MAX_TURNS,
    MIN_AREA_M2: MIN_AREA_M2,
    MAX_AREA_M2: MAX_AREA_M2,
    MIN_FIELD_T: MIN_FIELD_T,
    MAX_FIELD_T: MAX_FIELD_T,
    MIN_TIME_INTERVAL_S: MIN_TIME_INTERVAL_S,
    MAX_TIME_INTERVAL_S: MAX_TIME_INTERVAL_S,
    clampTurns: clampTurns,
    clampArea: clampArea,
    clampField: clampField,
    clampTimeInterval: clampTimeInterval,
    computeState: computeState
  };
})(window, document);
