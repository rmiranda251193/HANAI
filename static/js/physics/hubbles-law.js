/**
 * Hubble's Law simulation.
 *
 * v = H0 d           (recession speed of a distant galaxy is directly
 *                      proportional to its distance -- the observational
 *                      evidence that space itself is expanding)
 * z = v / c           (redshift -- the fractional stretch in the galaxy's
 *                      light an astronomer actually measures with a
 *                      spectrograph; v is never observed directly)
 *
 * H0 (the Hubble constant, km/s/Mpc) is treated as a genuine adjustable
 * measurement, not a fixed constant -- real estimates currently disagree,
 * placing it somewhere around 67-74 km/s/Mpc (the "Hubble tension").
 * Distance is deliberately capped at 200 Mpc, well short of the ~4300 Mpc
 * Hubble distance (c / H0): a much larger range would let v = H0 d exceed
 * the speed of light at the UI's own upper corner, which would break this
 * lab's own "non-relativistic, z = v/c is an accurate approximation"
 * framing (see simulations_hubbles_law.py for the full reasoning). No
 * branching case here at all -- distance and H0 are both always positive,
 * so recession speed and redshift are always positive and well-defined,
 * unlike Coulomb's Law/Refraction/Photoelectric Effect/Bohr Model's
 * sentinel-value-plus-flag pairs. Like circuits.js/coulombs-law.js/
 * buoyancy.js/refraction.js/calorimetry.js/ideal-gas-law.js/
 * doppler-effect.js/time-dilation.js/photoelectric-effect.js/
 * bohr-model.js, there is no time axis and no run loop: values are
 * recomputed live on every control change. Always computed here, in
 * code -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_hubbles_law.py exactly (same bounds, same
 * constants, same formula). This file owns its own physics, SVG and
 * controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var SPEED_OF_LIGHT_KM_S = 299792.458;

  var MIN_DISTANCE_MPC = 1.0;
  var MAX_DISTANCE_MPC = 200.0;
  var MIN_HUBBLE_CONSTANT_KM_S_MPC = 60.0;
  var MAX_HUBBLE_CONSTANT_KM_S_MPC = 80.0;

  function clampDistance(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_DISTANCE_MPC, Math.min(MAX_DISTANCE_MPC, n));
  }
  function clampHubbleConstant(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_HUBBLE_CONSTANT_KM_S_MPC, Math.min(MAX_HUBBLE_CONSTANT_KM_S_MPC, n));
  }

  function computeState(distanceMpc, hubbleConstantKmSMpc) {
    var d = clampDistance(distanceMpc);
    var h0 = clampHubbleConstant(hubbleConstantKmSMpc);
    var recessionVelocity = h0 * d;
    var redshift = recessionVelocity / SPEED_OF_LIGHT_KM_S;
    return {
      distanceMpc: d,
      hubbleConstantKmSMpc: h0,
      recessionVelocityKmS: recessionVelocity,
      redshiftZ: redshift
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createHubblesLawSim(root, config, lab) {
    var state = {
      distanceMpc: clampDistance(readNum(root, "distance", 100)),
      hubbleConstantKmSMpc: clampHubbleConstant(readNum(root, "hubble-constant", 70))
    };
    var computed = computeState(state.distanceMpc, state.hubbleConstantKmSMpc);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      galaxy: root.querySelector("[data-galaxy]"),
      arrow: root.querySelector("[data-recession-arrow]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueDistance: root.querySelector("[data-value-distance]"),
      valueHubbleConstant: root.querySelector("[data-value-hubble-constant]"),
      valueVelocity: root.querySelector("[data-value-velocity]"),
      valueRedshift: root.querySelector("[data-value-redshift]"),
      eqVelocity: root.querySelector("[data-eq-velocity]"),
      outDistance: root.querySelector("[data-out-distance]"),
      outHubbleConstant: root.querySelector("[data-out-hubble-constant]"),
      inputDistance: root.querySelector("[data-input-distance]"),
      inputHubbleConstant: root.querySelector("[data-input-hubble-constant]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.distanceMpc, state.hubbleConstantKmSMpc);
    }

    function setDistance(value) {
      state.distanceMpc = clampDistance(value);
      if (el.inputDistance) el.inputDistance.value = String(state.distanceMpc);
      if (el.outDistance) el.outDistance.textContent = String(state.distanceMpc);
      recompute();
      render();
    }
    function setHubbleConstant(value) {
      state.hubbleConstantKmSMpc = clampHubbleConstant(value);
      if (el.inputHubbleConstant) el.inputHubbleConstant.value = String(state.hubbleConstantKmSMpc);
      if (el.outHubbleConstant) el.outHubbleConstant.textContent = String(state.hubbleConstantKmSMpc);
      recompute();
      render();
    }
    function reset() {
      setDistance(100);
      setHubbleConstant(70);
    }

    function renderScene() {
      var leftX = 50, rightLimitX = 370;
      var frac = (computed.distanceMpc - MIN_DISTANCE_MPC) / (MAX_DISTANCE_MPC - MIN_DISTANCE_MPC);
      var galaxyX = leftX + frac * (rightLimitX - leftX);
      if (el.galaxy) {
        el.galaxy.setAttribute("cx", String(galaxyX));
      }
      if (el.arrow) {
        el.arrow.setAttribute("x1", String(galaxyX + 10));
        el.arrow.setAttribute("x2", String(Math.min(rightLimitX + 20, galaxyX + 20 + computed.recessionVelocityKmS / 400)));
      }
      var text =
        "A galaxy at " + computed.distanceMpc.toFixed(1) + " megaparsecs recedes at " +
        computed.recessionVelocityKmS.toFixed(0) + " kilometres per second, redshifted by z = " +
        computed.redshiftZ.toFixed(5) + ".";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
      if (el.sceneStatus) el.sceneStatus.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 50, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var maxVelocity = MAX_HUBBLE_CONSTANT_KM_S_MPC * MAX_DISTANCE_MPC;
      var samples = 2;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var d = (MAX_DISTANCE_MPC * i) / samples;
        var v = computed.hubbleConstantKmSMpc * d;
        var px = left + (d / MAX_DISTANCE_MPC) * plotW;
        var py = top + plotH - (v / maxVelocity) * plotH;
        points.push(px.toFixed(1) + "," + py.toFixed(1));
      }
      el.curve.setAttribute("points", points.join(" "));
      if (el.marker) {
        var mx = left + (computed.distanceMpc / MAX_DISTANCE_MPC) * plotW;
        var my = top + plotH - (computed.recessionVelocityKmS / maxVelocity) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "A graph of recession speed against distance -- the Hubble diagram. It is a straight " +
        "line through the origin whose slope is the Hubble constant.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueDistance) el.valueDistance.textContent = state.distanceMpc.toFixed(1);
      if (el.valueHubbleConstant) el.valueHubbleConstant.textContent = state.hubbleConstantKmSMpc.toFixed(1);
      if (el.valueVelocity) el.valueVelocity.textContent = computed.recessionVelocityKmS.toFixed(0);
      if (el.valueRedshift) el.valueRedshift.textContent = computed.redshiftZ.toFixed(5);
      if (el.eqVelocity) el.eqVelocity.textContent = computed.recessionVelocityKmS.toFixed(0);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        distanceMpc: state.distanceMpc,
        hubbleConstantKmSMpc: state.hubbleConstantKmSMpc,
        recessionVelocityKmS: computed.recessionVelocityKmS,
        redshiftZ: computed.redshiftZ,
        running: false
      };
    }

    if (el.inputDistance) {
      el.inputDistance.addEventListener("input", function () { setDistance(el.inputDistance.value); });
      el.inputDistance.addEventListener("change", function () { setDistance(el.inputDistance.value); });
    }
    if (el.inputHubbleConstant) {
      el.inputHubbleConstant.addEventListener("input", function () { setHubbleConstant(el.inputHubbleConstant.value); });
      el.inputHubbleConstant.addEventListener("change", function () { setHubbleConstant(el.inputHubbleConstant.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setDistance: setDistance,
      setHubbleConstant: setHubbleConstant,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("hubbles_law", createHubblesLawSim);

  PhysicsLab.HubblesLaw = {
    SPEED_OF_LIGHT_KM_S: SPEED_OF_LIGHT_KM_S,
    MIN_DISTANCE_MPC: MIN_DISTANCE_MPC,
    MAX_DISTANCE_MPC: MAX_DISTANCE_MPC,
    MIN_HUBBLE_CONSTANT_KM_S_MPC: MIN_HUBBLE_CONSTANT_KM_S_MPC,
    MAX_HUBBLE_CONSTANT_KM_S_MPC: MAX_HUBBLE_CONSTANT_KM_S_MPC,
    clampDistance: clampDistance,
    clampHubbleConstant: clampHubbleConstant,
    computeState: computeState
  };
})(window, document);
