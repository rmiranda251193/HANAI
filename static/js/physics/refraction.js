/**
 * Refraction (Snell's Law) simulation.
 *
 * n1 * sin(theta1) = n2 * sin(theta2)
 *
 * Going from a denser medium into a less dense one (n1 > n2), past the
 * critical angle = arcsin(n2 / n1), NO refracted ray exists -- all the
 * light undergoes total internal reflection back into medium 1 instead.
 * angle2 = 0 during TIR is a sentinel, not a real angle -- always check
 * totalInternalReflection first, exactly like coulombs-law.js's zero-
 * force/isAttractive convention. Like circuits.js/coulombs-law.js/
 * buoyancy.js, there is no time axis and no run loop: values are
 * recomputed live on every control change. Always computed here, in code
 * -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_refraction.py exactly (same bounds, same
 * formulas). This file owns its own physics, SVG and controls; it shares
 * only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_INDEX = 1.0;
  var MAX_INDEX = 2.5;
  var MIN_ANGLE_DEG = 0.0;
  var MAX_ANGLE_DEG = 89.0;

  function clampIndex(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_INDEX, Math.min(MAX_INDEX, n));
  }
  function clampAngle(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_ANGLE_DEG, Math.min(MAX_ANGLE_DEG, n));
  }

  function computeState(n1, n2, angle1Deg) {
    var n1c = clampIndex(n1);
    var n2c = clampIndex(n2);
    var theta1Deg = clampAngle(angle1Deg);
    var theta1Rad = (theta1Deg * Math.PI) / 180;

    var hasCriticalAngle = n1c > n2c;
    var criticalAngleDeg = hasCriticalAngle ? (Math.asin(n2c / n1c) * 180) / Math.PI : 0;

    var sinTheta2 = (n1c / n2c) * Math.sin(theta1Rad);
    var totalInternalReflection = sinTheta2 > 1.0;
    var angle2Deg = totalInternalReflection ? 0 : (Math.asin(Math.min(1, sinTheta2)) * 180) / Math.PI;

    return {
      n1: n1c,
      n2: n2c,
      angle1Deg: theta1Deg,
      hasCriticalAngle: hasCriticalAngle,
      criticalAngleDeg: criticalAngleDeg,
      totalInternalReflection: totalInternalReflection,
      angle2Deg: angle2Deg
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createRefractionSim(root, config, lab) {
    var state = {
      n1: clampIndex(readNum(root, "n1", 1.0)),
      n2: clampIndex(readNum(root, "n2", 1.5)),
      angle1: clampAngle(readNum(root, "angle1", 30))
    };
    var computed = computeState(state.n1, state.n2, state.angle1);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      incidentRay: root.querySelector("[data-incident-ray]"),
      outgoingRay: root.querySelector("[data-outgoing-ray]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueN1: root.querySelector("[data-value-n1]"),
      valueN2: root.querySelector("[data-value-n2]"),
      valueAngle1: root.querySelector("[data-value-angle1]"),
      valueAngle2: root.querySelector("[data-value-angle2]"),
      valueOutcome: root.querySelector("[data-value-outcome]"),
      valueCritical: root.querySelector("[data-value-critical]"),
      eqAngle2: root.querySelector("[data-eq-angle2]"),
      outN1: root.querySelector("[data-out-n1]"),
      outN2: root.querySelector("[data-out-n2]"),
      outAngle1: root.querySelector("[data-out-angle1]"),
      inputN1: root.querySelector("[data-input-n1]"),
      inputN2: root.querySelector("[data-input-n2]"),
      inputAngle1: root.querySelector("[data-input-angle1]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.n1, state.n2, state.angle1);
    }

    function setN1(value) {
      state.n1 = clampIndex(value);
      if (el.inputN1) el.inputN1.value = String(state.n1);
      if (el.outN1) el.outN1.textContent = String(state.n1);
      recompute();
      render();
    }
    function setN2(value) {
      state.n2 = clampIndex(value);
      if (el.inputN2) el.inputN2.value = String(state.n2);
      if (el.outN2) el.outN2.textContent = String(state.n2);
      recompute();
      render();
    }
    function setAngle1(value) {
      state.angle1 = clampAngle(value);
      if (el.inputAngle1) el.inputAngle1.value = String(state.angle1);
      if (el.outAngle1) el.outAngle1.textContent = String(state.angle1);
      recompute();
      render();
    }
    function reset() {
      setN1(1.0);
      setN2(1.5);
      setAngle1(30);
    }

    function renderScene() {
      var cx = 200, cy = 110, rayLen = 80;
      var theta1Rad = (state.angle1 * Math.PI) / 180;
      var startX = cx - rayLen * Math.sin(theta1Rad);
      var startY = cy - rayLen * Math.cos(theta1Rad);
      if (el.incidentRay) {
        el.incidentRay.setAttribute("x1", startX.toFixed(1));
        el.incidentRay.setAttribute("y1", startY.toFixed(1));
        el.incidentRay.setAttribute("x2", String(cx));
        el.incidentRay.setAttribute("y2", String(cy));
      }
      if (el.outgoingRay) {
        var endX, endY;
        if (computed.totalInternalReflection) {
          var reflectRad = (state.angle1 * Math.PI) / 180;
          endX = cx + rayLen * Math.sin(reflectRad);
          endY = cy - rayLen * Math.cos(reflectRad);
        } else {
          var theta2Rad = (computed.angle2Deg * Math.PI) / 180;
          endX = cx + rayLen * Math.sin(theta2Rad);
          endY = cy + rayLen * Math.cos(theta2Rad);
        }
        el.outgoingRay.setAttribute("x1", String(cx));
        el.outgoingRay.setAttribute("y1", String(cy));
        el.outgoingRay.setAttribute("x2", endX.toFixed(1));
        el.outgoingRay.setAttribute("y2", endY.toFixed(1));
      }
      var text = computed.totalInternalReflection
        ? "A ray hits the interface at " + state.angle1.toFixed(0) + " degrees from the normal and totally internally reflects -- no refracted ray."
        : "A ray hits the interface at " + state.angle1.toFixed(0) + " degrees from the normal and refracts to " + computed.angle2Deg.toFixed(0) + " degrees from the normal.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
      if (el.sceneStatus) {
        el.sceneStatus.textContent = computed.totalInternalReflection
          ? "Total internal reflection -- all light reflects back."
          : "";
      }
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var limitDeg = computed.hasCriticalAngle ? Math.min(MAX_ANGLE_DEG, computed.criticalAngleDeg) : MAX_ANGLE_DEG;
      var samples = 40;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var a1 = (limitDeg * i) / samples;
        var c = computeState(state.n1, state.n2, a1);
        if (c.totalInternalReflection) break;
        points.push([a1, c.angle2Deg]);
      }
      var path = points.map(function (p) {
        var px = left + (p[0] / MAX_ANGLE_DEG) * plotW;
        var py = top + plotH - (p[1] / 90) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        if (computed.totalInternalReflection) {
          el.marker.setAttribute("cx", "-10");
          el.marker.setAttribute("cy", "-10");
        } else {
          var mx = left + (state.angle1 / MAX_ANGLE_DEG) * plotW;
          var my = top + plotH - (computed.angle2Deg / 90) * plotH;
          el.marker.setAttribute("cx", mx.toFixed(1));
          el.marker.setAttribute("cy", my.toFixed(1));
        }
      }
      var graphText = "Refraction angle versus angle of incidence, for these two refractive indices." +
        (computed.hasCriticalAngle ? " The curve stops at the critical angle of " + computed.criticalAngleDeg.toFixed(1) + " degrees, past which there is no refracted ray." : "");
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueN1) el.valueN1.textContent = state.n1.toFixed(2);
      if (el.valueN2) el.valueN2.textContent = state.n2.toFixed(2);
      if (el.valueAngle1) el.valueAngle1.textContent = state.angle1.toFixed(1);
      if (el.valueAngle2) {
        el.valueAngle2.textContent = computed.totalInternalReflection ? "–" : computed.angle2Deg.toFixed(1);
      }
      if (el.valueOutcome) {
        el.valueOutcome.textContent = computed.totalInternalReflection ? "Total internal reflection" : "Refracts";
      }
      if (el.valueCritical) {
        el.valueCritical.textContent = computed.hasCriticalAngle ? computed.criticalAngleDeg.toFixed(1) + "°" : "n/a";
      }
      if (el.eqAngle2) {
        el.eqAngle2.textContent = computed.totalInternalReflection ? "TIR" : computed.angle2Deg.toFixed(1);
      }
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        n1: state.n1,
        n2: state.n2,
        angle1Deg: state.angle1,
        angle2Deg: computed.angle2Deg,
        running: false
      };
    }

    if (el.inputN1) {
      el.inputN1.addEventListener("input", function () { setN1(el.inputN1.value); });
      el.inputN1.addEventListener("change", function () { setN1(el.inputN1.value); });
    }
    if (el.inputN2) {
      el.inputN2.addEventListener("input", function () { setN2(el.inputN2.value); });
      el.inputN2.addEventListener("change", function () { setN2(el.inputN2.value); });
    }
    if (el.inputAngle1) {
      el.inputAngle1.addEventListener("input", function () { setAngle1(el.inputAngle1.value); });
      el.inputAngle1.addEventListener("change", function () { setAngle1(el.inputAngle1.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setN1: setN1,
      setN2: setN2,
      setAngle1: setAngle1,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("refraction", createRefractionSim);

  PhysicsLab.Refraction = {
    MIN_INDEX: MIN_INDEX,
    MAX_INDEX: MAX_INDEX,
    MIN_ANGLE_DEG: MIN_ANGLE_DEG,
    MAX_ANGLE_DEG: MAX_ANGLE_DEG,
    clampIndex: clampIndex,
    clampAngle: clampAngle,
    computeState: computeState
  };
})(window, document);
