/**
 * The Doppler Effect simulation.
 *
 * f_observed = f_source * (v_sound + v_observer) / (v_sound - v_source)
 *
 * v_source and v_observer are signed: positive means moving TOWARD the
 * other party, negative means moving away. Source motion and observer
 * motion enter the formula differently (source in the denominator,
 * observer in the numerator) -- they do NOT produce the same shift at the
 * same speed, which is real physics, not an approximation error. Like
 * circuits.js/coulombs-law.js/buoyancy.js/refraction.js/calorimetry.js/
 * ideal-gas-law.js, there is no time axis and no run loop: values are
 * recomputed live on every control change. Always computed here, in code
 * -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_doppler_effect.py exactly (same bounds, same
 * speed of sound, same formula). This file owns its own physics, SVG and
 * controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var SPEED_OF_SOUND_M_S = 343.0;
  var MIN_FREQ_HZ = 20.0;
  var MAX_FREQ_HZ = 2000.0;
  var MAX_VELOCITY_M_S = 60.0;

  function clampFreq(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_FREQ_HZ, Math.min(MAX_FREQ_HZ, n));
  }
  function clampVelocity(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(-MAX_VELOCITY_M_S, Math.min(MAX_VELOCITY_M_S, n));
  }

  function computeState(sourceFreq, sourceVelocity, observerVelocity) {
    var fSource = clampFreq(sourceFreq);
    var vSource = clampVelocity(sourceVelocity);
    var vObserver = clampVelocity(observerVelocity);
    var fObserved = (fSource * (SPEED_OF_SOUND_M_S + vObserver)) / (SPEED_OF_SOUND_M_S - vSource);
    var wavelengthAhead = (SPEED_OF_SOUND_M_S - vSource) / fSource;
    var wavelengthBehind = (SPEED_OF_SOUND_M_S + vSource) / fSource;
    return {
      sourceFreq: fSource,
      sourceVelocity: vSource,
      observerVelocity: vObserver,
      observedFreq: fObserved,
      wavelengthAhead: wavelengthAhead,
      wavelengthBehind: wavelengthBehind
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createDopplerSim(root, config, lab) {
    var state = {
      sourceFreq: clampFreq(readNum(root, "source-freq", 440)),
      sourceVelocity: clampVelocity(readNum(root, "source-velocity", 20)),
      observerVelocity: clampVelocity(readNum(root, "observer-velocity", 0))
    };
    var computed = computeState(state.sourceFreq, state.sourceVelocity, state.observerVelocity);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      wavefronts: root.querySelector("[data-wavefronts]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueSourceFreq: root.querySelector("[data-value-source-freq]"),
      valueSourceVelocity: root.querySelector("[data-value-source-velocity]"),
      valueObserverVelocity: root.querySelector("[data-value-observer-velocity]"),
      valueObservedFreq: root.querySelector("[data-value-observed-freq]"),
      eqObserved: root.querySelector("[data-eq-observed]"),
      outSourceFreq: root.querySelector("[data-out-source-freq]"),
      outSourceVelocity: root.querySelector("[data-out-source-velocity]"),
      outObserverVelocity: root.querySelector("[data-out-observer-velocity]"),
      inputSourceFreq: root.querySelector("[data-input-source-freq]"),
      inputSourceVelocity: root.querySelector("[data-input-source-velocity]"),
      inputObserverVelocity: root.querySelector("[data-input-observer-velocity]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.sourceFreq, state.sourceVelocity, state.observerVelocity);
    }

    function setSourceFreq(value) {
      state.sourceFreq = clampFreq(value);
      if (el.inputSourceFreq) el.inputSourceFreq.value = String(state.sourceFreq);
      if (el.outSourceFreq) el.outSourceFreq.textContent = String(state.sourceFreq);
      recompute();
      render();
    }
    function setSourceVelocity(value) {
      state.sourceVelocity = clampVelocity(value);
      if (el.inputSourceVelocity) el.inputSourceVelocity.value = String(state.sourceVelocity);
      if (el.outSourceVelocity) el.outSourceVelocity.textContent = String(state.sourceVelocity);
      recompute();
      render();
    }
    function setObserverVelocity(value) {
      state.observerVelocity = clampVelocity(value);
      if (el.inputObserverVelocity) el.inputObserverVelocity.value = String(state.observerVelocity);
      if (el.outObserverVelocity) el.outObserverVelocity.textContent = String(state.observerVelocity);
      recompute();
      render();
    }
    function reset() {
      setSourceFreq(440);
      setSourceVelocity(20);
      setObserverVelocity(0);
    }

    function renderScene() {
      if (el.wavefronts) {
        while (el.wavefronts.firstChild) el.wavefronts.removeChild(el.wavefronts.firstChild);
        var maxWavelength = Math.max(computed.wavelengthAhead, computed.wavelengthBehind, 0.01);
        var pxPerMeter = 150 / (5 * maxWavelength);
        var i, x;
        for (i = 1; i <= 8; i++) {
          x = 200 + i * computed.wavelengthAhead * pxPerMeter;
          if (x > 390) break;
          el.wavefronts.appendChild(makeTick(x));
        }
        for (i = 1; i <= 8; i++) {
          x = 200 - i * computed.wavelengthBehind * pxPerMeter;
          if (x < 10) break;
          el.wavefronts.appendChild(makeTick(x));
        }
      }
      var text =
        "A source emitting " + state.sourceFreq.toFixed(0) + " hertz, moving at " +
        state.sourceVelocity.toFixed(1) + " metres per second (positive means approaching). " +
        "The observer hears " + computed.observedFreq.toFixed(1) + " hertz.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function makeTick(x) {
      var ns = "http://www.w3.org/2000/svg";
      var line = document.createElementNS(ns, "line");
      line.setAttribute("x1", x.toFixed(1));
      line.setAttribute("y1", "40");
      line.setAttribute("x2", x.toFixed(1));
      line.setAttribute("y2", "120");
      line.setAttribute("class", "lab-track");
      return line;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var samples = 40;
      var points = [];
      var minF = Infinity, maxF = -Infinity;
      for (var i = 0; i <= samples; i++) {
        var vs = -MAX_VELOCITY_M_S + ((2 * MAX_VELOCITY_M_S) * i) / samples;
        var c = computeState(state.sourceFreq, vs, state.observerVelocity);
        points.push([vs, c.observedFreq]);
        if (c.observedFreq < minF) minF = c.observedFreq;
        if (c.observedFreq > maxF) maxF = c.observedFreq;
      }
      var path = points.map(function (p) {
        var px = left + ((p[0] + MAX_VELOCITY_M_S) / (2 * MAX_VELOCITY_M_S)) * plotW;
        var py = top + plotH - ((p[1] - minF) / Math.max(1e-9, maxF - minF)) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        var mx = left + ((state.sourceVelocity + MAX_VELOCITY_M_S) / (2 * MAX_VELOCITY_M_S)) * plotW;
        var my = top + plotH - ((computed.observedFreq - minF) / Math.max(1e-9, maxF - minF)) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "Observed frequency versus source velocity, at the current source frequency and observer velocity.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueSourceFreq) el.valueSourceFreq.textContent = state.sourceFreq.toFixed(0);
      if (el.valueSourceVelocity) el.valueSourceVelocity.textContent = state.sourceVelocity.toFixed(1);
      if (el.valueObserverVelocity) el.valueObserverVelocity.textContent = state.observerVelocity.toFixed(1);
      if (el.valueObservedFreq) el.valueObservedFreq.textContent = computed.observedFreq.toFixed(1);
      if (el.eqObserved) el.eqObserved.textContent = computed.observedFreq.toFixed(1);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        sourceFreqHz: state.sourceFreq,
        sourceVelocityMS: state.sourceVelocity,
        observerVelocityMS: state.observerVelocity,
        observedFreqHz: computed.observedFreq,
        running: false
      };
    }

    if (el.inputSourceFreq) {
      el.inputSourceFreq.addEventListener("input", function () { setSourceFreq(el.inputSourceFreq.value); });
      el.inputSourceFreq.addEventListener("change", function () { setSourceFreq(el.inputSourceFreq.value); });
    }
    if (el.inputSourceVelocity) {
      el.inputSourceVelocity.addEventListener("input", function () { setSourceVelocity(el.inputSourceVelocity.value); });
      el.inputSourceVelocity.addEventListener("change", function () { setSourceVelocity(el.inputSourceVelocity.value); });
    }
    if (el.inputObserverVelocity) {
      el.inputObserverVelocity.addEventListener("input", function () { setObserverVelocity(el.inputObserverVelocity.value); });
      el.inputObserverVelocity.addEventListener("change", function () { setObserverVelocity(el.inputObserverVelocity.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setSourceFreq: setSourceFreq,
      setSourceVelocity: setSourceVelocity,
      setObserverVelocity: setObserverVelocity,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("doppler_effect", createDopplerSim);

  PhysicsLab.DopplerEffect = {
    SPEED_OF_SOUND_M_S: SPEED_OF_SOUND_M_S,
    MIN_FREQ_HZ: MIN_FREQ_HZ,
    MAX_FREQ_HZ: MAX_FREQ_HZ,
    MAX_VELOCITY_M_S: MAX_VELOCITY_M_S,
    clampFreq: clampFreq,
    clampVelocity: clampVelocity,
    computeState: computeState
  };
})(window, document);
