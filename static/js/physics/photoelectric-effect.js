/**
 * The Photoelectric Effect simulation.
 *
 * frequency = c / wavelength
 * E_photon = h * frequency          (h in eV*s -- the real Planck's constant)
 * KE_max = E_photon - workFunction  (0 and no ejection if this would be negative)
 *
 * Intensity only scales how MANY electrons are ejected per second when
 * ejection is already happening -- it has ZERO effect on KE_max, and
 * produces exactly zero electrons, at ANY intensity, below the threshold.
 * That is the exact misconception the seeded concept names. Like
 * circuits.js/coulombs-law.js/buoyancy.js/refraction.js/calorimetry.js/
 * ideal-gas-law.js/doppler-effect.js/time-dilation.js, there is no time
 * axis and no run loop: values are recomputed live on every control
 * change. Always computed here, in code -- never fetched from a server
 * and never generated by AI. Mirrors
 * apps/physics/simulations_photoelectric_effect.py exactly (same bounds,
 * same constants, same formula). This file owns its own physics, SVG and
 * controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var SPEED_OF_LIGHT_M_S = 3.0e8;
  var PLANCK_CONSTANT_EV_S = 4.135667696e-15;
  var MIN_WAVELENGTH_NM = 100.0;
  var MAX_WAVELENGTH_NM = 700.0;
  var MIN_WORK_FUNCTION_EV = 1.0;
  var MAX_WORK_FUNCTION_EV = 6.0;
  var MIN_INTENSITY = 1.0;
  var MAX_INTENSITY = 10.0;

  function clampWavelength(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_WAVELENGTH_NM, Math.min(MAX_WAVELENGTH_NM, n));
  }
  function clampWorkFunction(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_WORK_FUNCTION_EV, Math.min(MAX_WORK_FUNCTION_EV, n));
  }
  function clampIntensity(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_INTENSITY, Math.min(MAX_INTENSITY, n));
  }

  function computeState(wavelengthNm, workFunctionEv, intensity) {
    var wavelength = clampWavelength(wavelengthNm);
    var phi = clampWorkFunction(workFunctionEv);
    var intensityC = clampIntensity(intensity);

    var frequency = SPEED_OF_LIGHT_M_S / (wavelength * 1e-9);
    var photonEnergy = PLANCK_CONSTANT_EV_S * frequency;
    var keMaxRaw = photonEnergy - phi;
    var ejects = keMaxRaw > 0;
    var keMax = Math.max(0, keMaxRaw);
    var rate = ejects ? intensityC : 0;
    var thresholdFrequency = phi / PLANCK_CONSTANT_EV_S;
    var thresholdWavelength = (SPEED_OF_LIGHT_M_S / thresholdFrequency) * 1e9;

    return {
      wavelength: wavelength,
      workFunction: phi,
      intensity: intensityC,
      frequency: frequency,
      photonEnergy: photonEnergy,
      ejectsElectrons: ejects,
      keMax: keMax,
      photoelectronRate: rate,
      thresholdWavelength: thresholdWavelength
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createPhotoelectricSim(root, config, lab) {
    var state = {
      wavelength: clampWavelength(readNum(root, "wavelength", 400)),
      workFunction: clampWorkFunction(readNum(root, "work-function", 2.3)),
      intensity: clampIntensity(readNum(root, "intensity", 5))
    };
    var computed = computeState(state.wavelength, state.workFunction, state.intensity);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      electron: root.querySelector("[data-electron]"),
      blockedNote: root.querySelector("[data-blocked-note]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueWavelength: root.querySelector("[data-value-wavelength]"),
      valueWorkFunction: root.querySelector("[data-value-work-function]"),
      valueIntensity: root.querySelector("[data-value-intensity]"),
      valuePhotonEnergy: root.querySelector("[data-value-photon-energy]"),
      valueOutcome: root.querySelector("[data-value-outcome]"),
      valueKeMax: root.querySelector("[data-value-ke-max]"),
      valueRate: root.querySelector("[data-value-rate]"),
      eqKeMax: root.querySelector("[data-eq-ke-max]"),
      outWavelength: root.querySelector("[data-out-wavelength]"),
      outWorkFunction: root.querySelector("[data-out-work-function]"),
      outIntensity: root.querySelector("[data-out-intensity]"),
      inputWavelength: root.querySelector("[data-input-wavelength]"),
      inputWorkFunction: root.querySelector("[data-input-work-function]"),
      inputIntensity: root.querySelector("[data-input-intensity]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.wavelength, state.workFunction, state.intensity);
    }

    function setWavelength(value) {
      state.wavelength = clampWavelength(value);
      if (el.inputWavelength) el.inputWavelength.value = String(state.wavelength);
      if (el.outWavelength) el.outWavelength.textContent = String(state.wavelength);
      recompute();
      render();
    }
    function setWorkFunction(value) {
      state.workFunction = clampWorkFunction(value);
      if (el.inputWorkFunction) el.inputWorkFunction.value = String(state.workFunction);
      if (el.outWorkFunction) el.outWorkFunction.textContent = String(state.workFunction);
      recompute();
      render();
    }
    function setIntensity(value) {
      state.intensity = clampIntensity(value);
      if (el.inputIntensity) el.inputIntensity.value = String(state.intensity);
      if (el.outIntensity) el.outIntensity.textContent = String(state.intensity);
      recompute();
      render();
    }
    function reset() {
      setWavelength(400);
      setWorkFunction(2.3);
      setIntensity(5);
    }

    function renderScene() {
      if (el.electron) el.electron.setAttribute("visibility", computed.ejectsElectrons ? "visible" : "hidden");
      if (el.blockedNote) el.blockedNote.setAttribute("visibility", computed.ejectsElectrons ? "hidden" : "visible");
      var text = computed.ejectsElectrons
        ? "Light at " + state.wavelength.toFixed(0) + " nanometres ejects an electron with maximum kinetic energy " + computed.keMax.toFixed(2) + " electron-volts."
        : "Light at " + state.wavelength.toFixed(0) + " nanometres cannot eject any electrons from this metal, no matter how intense it is.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var fMin = SPEED_OF_LIGHT_M_S / (MAX_WAVELENGTH_NM * 1e-9);
      var fMax = SPEED_OF_LIGHT_M_S / (MIN_WAVELENGTH_NM * 1e-9);
      var samples = 40;
      var maxKe = 1e-9;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var f = fMin + ((fMax - fMin) * i) / samples;
        var e = PLANCK_CONSTANT_EV_S * f;
        var ke = Math.max(0, e - state.workFunction);
        points.push([f, ke]);
        if (ke > maxKe) maxKe = ke;
      }
      var path = points.map(function (p) {
        var px = left + ((p[0] - fMin) / (fMax - fMin)) * plotW;
        var py = top + plotH - (p[1] / maxKe) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        var mx = left + ((computed.frequency - fMin) / (fMax - fMin)) * plotW;
        var my = top + plotH - (computed.keMax / maxKe) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "Maximum kinetic energy versus light frequency, for this work function. " +
        "A straight line that only starts rising past the threshold frequency.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueWavelength) el.valueWavelength.textContent = state.wavelength.toFixed(0);
      if (el.valueWorkFunction) el.valueWorkFunction.textContent = state.workFunction.toFixed(2);
      if (el.valueIntensity) el.valueIntensity.textContent = state.intensity.toFixed(1);
      if (el.valuePhotonEnergy) el.valuePhotonEnergy.textContent = computed.photonEnergy.toFixed(2);
      if (el.valueOutcome) el.valueOutcome.textContent = computed.ejectsElectrons ? "Ejects electrons" : "No ejection";
      if (el.valueKeMax) el.valueKeMax.textContent = computed.keMax.toFixed(2);
      if (el.valueRate) el.valueRate.textContent = computed.photoelectronRate.toFixed(1);
      if (el.eqKeMax) el.eqKeMax.textContent = computed.keMax.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        wavelengthNm: state.wavelength,
        workFunctionEv: state.workFunction,
        intensity: state.intensity,
        photonEnergyEv: computed.photonEnergy,
        ejectsElectrons: computed.ejectsElectrons ? 1 : 0,
        keMaxEv: computed.keMax,
        photoelectronRate: computed.photoelectronRate,
        running: false
      };
    }

    if (el.inputWavelength) {
      el.inputWavelength.addEventListener("input", function () { setWavelength(el.inputWavelength.value); });
      el.inputWavelength.addEventListener("change", function () { setWavelength(el.inputWavelength.value); });
    }
    if (el.inputWorkFunction) {
      el.inputWorkFunction.addEventListener("input", function () { setWorkFunction(el.inputWorkFunction.value); });
      el.inputWorkFunction.addEventListener("change", function () { setWorkFunction(el.inputWorkFunction.value); });
    }
    if (el.inputIntensity) {
      el.inputIntensity.addEventListener("input", function () { setIntensity(el.inputIntensity.value); });
      el.inputIntensity.addEventListener("change", function () { setIntensity(el.inputIntensity.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setWavelength: setWavelength,
      setWorkFunction: setWorkFunction,
      setIntensity: setIntensity,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("photoelectric_effect", createPhotoelectricSim);

  PhysicsLab.PhotoelectricEffect = {
    SPEED_OF_LIGHT_M_S: SPEED_OF_LIGHT_M_S,
    PLANCK_CONSTANT_EV_S: PLANCK_CONSTANT_EV_S,
    MIN_WAVELENGTH_NM: MIN_WAVELENGTH_NM,
    MAX_WAVELENGTH_NM: MAX_WAVELENGTH_NM,
    MIN_WORK_FUNCTION_EV: MIN_WORK_FUNCTION_EV,
    MAX_WORK_FUNCTION_EV: MAX_WORK_FUNCTION_EV,
    MIN_INTENSITY: MIN_INTENSITY,
    MAX_INTENSITY: MAX_INTENSITY,
    clampWavelength: clampWavelength,
    clampWorkFunction: clampWorkFunction,
    clampIntensity: clampIntensity,
    computeState: computeState
  };
})(window, document);
