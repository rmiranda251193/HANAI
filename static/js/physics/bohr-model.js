/**
 * The Bohr Model simulation.
 *
 * E_n = -13.6 eV / n^2                 (13.6 eV -- the real ionization energy
 *                                        of hydrogen)
 * E_photon = |E_final - E_initial|
 * wavelength = 1239.84 eV*nm / E_photon (the real h*c product, in these
 *                                        units -- 0 and "no transition" when
 *                                        initial_level == final_level)
 *
 * The electron ABSORBS a photon jumping to a higher level, EMITS one
 * falling to a lower level. When the two levels are equal there is no
 * transition at all: photon energy and wavelength are both reported as
 * zero, together with a false hasTransition flag -- never interpret the
 * 0.0 alone, always check the flag first, the same convention
 * coulombs-law.js's zero-force/isAttractive pair and refraction.js's
 * zero-angle/totalInternalReflection pair use. Like circuits.js/
 * coulombs-law.js/buoyancy.js/refraction.js/calorimetry.js/
 * ideal-gas-law.js/doppler-effect.js/time-dilation.js/
 * photoelectric-effect.js, there is no time axis and no run loop: values
 * are recomputed live on every control change. Always computed here, in
 * code -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_bohr_model.py exactly (same bounds, same
 * constants, same formula). This file owns its own physics, SVG and
 * controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var RYDBERG_ENERGY_EV = 13.6;
  var HC_EV_NM = 1239.84;
  var MIN_LEVEL = 1;
  var MAX_LEVEL = 6;

  function clampLevel(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    var rounded = Math.round(n);
    return Math.max(MIN_LEVEL, Math.min(MAX_LEVEL, rounded));
  }

  function computeState(initialLevel, finalLevel) {
    var n1 = clampLevel(initialLevel);
    var n2 = clampLevel(finalLevel);

    var energyInitial = -RYDBERG_ENERGY_EV / (n1 * n1);
    var energyFinal = -RYDBERG_ENERGY_EV / (n2 * n2);
    var photonEnergy = Math.abs(energyFinal - energyInitial);
    var hasTransition = n1 !== n2;
    var isAbsorption = n2 > n1;
    var wavelength = hasTransition ? HC_EV_NM / photonEnergy : 0;

    return {
      initialLevel: n1,
      finalLevel: n2,
      energyInitialEv: energyInitial,
      energyFinalEv: energyFinal,
      photonEnergyEv: photonEnergy,
      hasTransition: hasTransition,
      isAbsorption: isAbsorption,
      wavelengthNm: wavelength
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createBohrModelSim(root, config, lab) {
    var state = {
      initialLevel: clampLevel(readNum(root, "initial-level", 3)),
      finalLevel: clampLevel(readNum(root, "final-level", 2))
    };
    var computed = computeState(state.initialLevel, state.finalLevel);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      electron: root.querySelector("[data-electron]"),
      photon: root.querySelector("[data-photon]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      valueInitialLevel: root.querySelector("[data-value-initial-level]"),
      valueFinalLevel: root.querySelector("[data-value-final-level]"),
      valueEnergyInitial: root.querySelector("[data-value-energy-initial]"),
      valueEnergyFinal: root.querySelector("[data-value-energy-final]"),
      valuePhotonEnergy: root.querySelector("[data-value-photon-energy]"),
      valueOutcome: root.querySelector("[data-value-outcome]"),
      valueWavelength: root.querySelector("[data-value-wavelength]"),
      eqPhoton: root.querySelector("[data-eq-photon]"),
      outInitialLevel: root.querySelector("[data-out-initial-level]"),
      outFinalLevel: root.querySelector("[data-out-final-level]"),
      inputInitialLevel: root.querySelector("[data-input-initial-level]"),
      inputFinalLevel: root.querySelector("[data-input-final-level]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function levelRadius(n) {
      return 16 + n * 12;
    }

    function recompute() {
      computed = computeState(state.initialLevel, state.finalLevel);
    }

    function setInitialLevel(value) {
      state.initialLevel = clampLevel(value);
      if (el.inputInitialLevel) el.inputInitialLevel.value = String(state.initialLevel);
      if (el.outInitialLevel) el.outInitialLevel.textContent = String(state.initialLevel);
      recompute();
      render();
    }
    function setFinalLevel(value) {
      state.finalLevel = clampLevel(value);
      if (el.inputFinalLevel) el.inputFinalLevel.value = String(state.finalLevel);
      if (el.outFinalLevel) el.outFinalLevel.textContent = String(state.finalLevel);
      recompute();
      render();
    }
    function reset() {
      setInitialLevel(3);
      setFinalLevel(2);
    }

    function renderScene() {
      var cx = 140, cy = 95;
      if (el.electron) {
        var r = levelRadius(computed.finalLevel);
        el.electron.setAttribute("cx", String(cx + r));
        el.electron.setAttribute("cy", String(cy));
      }
      if (el.photon) {
        var pr = levelRadius(computed.initialLevel);
        el.photon.setAttribute("x1", String(cx + pr));
        el.photon.setAttribute("y1", String(cy));
        el.photon.setAttribute("x2", String(cx + levelRadius(computed.finalLevel) + 30));
        el.photon.setAttribute("y2", String(cy - 20));
        el.photon.setAttribute("visibility", computed.hasTransition ? "visible" : "hidden");
      }
      var text;
      if (!computed.hasTransition) {
        text = "No transition -- the initial and final levels are the same, so no photon is involved.";
      } else {
        var verb = computed.isAbsorption ? "absorbs" : "emits";
        text = "The electron " + verb + " a photon of energy " + computed.photonEnergyEv.toFixed(2) +
          " electron-volts, wavelength " + computed.wavelengthNm.toFixed(1) + " nanometres, jumping from level " +
          computed.initialLevel + " to level " + computed.finalLevel + ".";
      }
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
      if (el.sceneStatus) el.sceneStatus.textContent = text;
    }

    function render() {
      if (el.valueInitialLevel) el.valueInitialLevel.textContent = String(state.initialLevel);
      if (el.valueFinalLevel) el.valueFinalLevel.textContent = String(state.finalLevel);
      if (el.valueEnergyInitial) el.valueEnergyInitial.textContent = computed.energyInitialEv.toFixed(2);
      if (el.valueEnergyFinal) el.valueEnergyFinal.textContent = computed.energyFinalEv.toFixed(2);
      if (el.valuePhotonEnergy) el.valuePhotonEnergy.textContent = computed.photonEnergyEv.toFixed(2);
      if (el.valueOutcome) {
        el.valueOutcome.textContent = !computed.hasTransition
          ? "No transition"
          : (computed.isAbsorption ? "Absorbs a photon" : "Emits a photon");
      }
      if (el.valueWavelength) el.valueWavelength.textContent = computed.hasTransition ? computed.wavelengthNm.toFixed(1) : "--";
      if (el.eqPhoton) el.eqPhoton.textContent = computed.photonEnergyEv.toFixed(2);
      renderScene();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        initialLevel: state.initialLevel,
        finalLevel: state.finalLevel,
        energyInitialEv: computed.energyInitialEv,
        energyFinalEv: computed.energyFinalEv,
        photonEnergyEv: computed.photonEnergyEv,
        hasTransition: computed.hasTransition ? 1 : 0,
        isAbsorption: computed.isAbsorption ? 1 : 0,
        wavelengthNm: computed.wavelengthNm,
        running: false
      };
    }

    if (el.inputInitialLevel) {
      el.inputInitialLevel.addEventListener("input", function () { setInitialLevel(el.inputInitialLevel.value); });
      el.inputInitialLevel.addEventListener("change", function () { setInitialLevel(el.inputInitialLevel.value); });
    }
    if (el.inputFinalLevel) {
      el.inputFinalLevel.addEventListener("input", function () { setFinalLevel(el.inputFinalLevel.value); });
      el.inputFinalLevel.addEventListener("change", function () { setFinalLevel(el.inputFinalLevel.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setInitialLevel: setInitialLevel,
      setFinalLevel: setFinalLevel,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("bohr_model", createBohrModelSim);

  PhysicsLab.BohrModel = {
    RYDBERG_ENERGY_EV: RYDBERG_ENERGY_EV,
    HC_EV_NM: HC_EV_NM,
    MIN_LEVEL: MIN_LEVEL,
    MAX_LEVEL: MAX_LEVEL,
    clampLevel: clampLevel,
    computeState: computeState
  };
})(window, document);
