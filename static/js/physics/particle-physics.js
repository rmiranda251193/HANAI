/**
 * Relativistic Energy and Momentum simulation.
 *
 * E^2 = (pc)^2 + (mc^2)^2        (the relativistic energy-momentum relation)
 * KE = E - mc^2                   (kinetic energy, always >= 0)
 * beta = pc / E                   (speed as a fraction of c, always < 1
 *                                  since rest energy mc^2 is required to
 *                                  be strictly positive here)
 *
 * Everything is expressed in MeV (momentum as pc, mass as mc^2), the
 * natural units particle physicists actually use -- no kilograms or
 * joules anywhere. No branching case here at all: rest energy is always
 * positive and momentum is always non-negative, so total energy, kinetic
 * energy and beta are always positive/non-negative and well-defined,
 * unlike Coulomb's Law/Refraction/Photoelectric Effect/Bohr Model's
 * sentinel-value-plus-flag pairs. Like circuits.js/coulombs-law.js/
 * buoyancy.js/refraction.js/calorimetry.js/ideal-gas-law.js/
 * doppler-effect.js/time-dilation.js/photoelectric-effect.js/
 * bohr-model.js/hubbles-law.js, there is no time axis and no run loop:
 * values are recomputed live on every control change. Always computed
 * here, in code -- never fetched from a server and never generated by
 * AI. Mirrors apps/physics/simulations_particle_physics.py exactly (same
 * bounds, same constants, same formula). This file owns its own physics,
 * SVG and controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_REST_ENERGY_MEV = 0.1;
  var MAX_REST_ENERGY_MEV = 1000.0;
  var MIN_MOMENTUM_MEV_C = 0.0;
  var MAX_MOMENTUM_MEV_C = 2000.0;

  function clampRestEnergy(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_REST_ENERGY_MEV, Math.min(MAX_REST_ENERGY_MEV, n));
  }
  function clampMomentum(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_MOMENTUM_MEV_C, Math.min(MAX_MOMENTUM_MEV_C, n));
  }

  function computeState(restEnergyMev, momentumMevC) {
    var mc2 = clampRestEnergy(restEnergyMev);
    var pc = clampMomentum(momentumMevC);
    var totalEnergy = Math.sqrt(pc * pc + mc2 * mc2);
    var kineticEnergy = totalEnergy - mc2;
    var beta = pc / totalEnergy;
    return {
      restEnergyMev: mc2,
      momentumMevC: pc,
      totalEnergyMev: totalEnergy,
      kineticEnergyMev: kineticEnergy,
      velocityFractionC: beta
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createParticlePhysicsSim(root, config, lab) {
    var state = {
      restEnergyMev: clampRestEnergy(readNum(root, "rest-energy", 105.66)),
      momentumMevC: clampMomentum(readNum(root, "momentum", 200))
    };
    var computed = computeState(state.restEnergyMev, state.momentumMevC);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      particle: root.querySelector("[data-particle]"),
      trail: root.querySelector("[data-speed-trail]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueRestEnergy: root.querySelector("[data-value-rest-energy]"),
      valueMomentum: root.querySelector("[data-value-momentum]"),
      valueTotalEnergy: root.querySelector("[data-value-total-energy]"),
      valueKineticEnergy: root.querySelector("[data-value-kinetic-energy]"),
      valueBeta: root.querySelector("[data-value-beta]"),
      eqTotalEnergy: root.querySelector("[data-eq-total-energy]"),
      outRestEnergy: root.querySelector("[data-out-rest-energy]"),
      outMomentum: root.querySelector("[data-out-momentum]"),
      inputRestEnergy: root.querySelector("[data-input-rest-energy]"),
      inputMomentum: root.querySelector("[data-input-momentum]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.restEnergyMev, state.momentumMevC);
    }

    function setRestEnergy(value) {
      state.restEnergyMev = clampRestEnergy(value);
      if (el.inputRestEnergy) el.inputRestEnergy.value = String(state.restEnergyMev);
      if (el.outRestEnergy) el.outRestEnergy.textContent = String(state.restEnergyMev);
      recompute();
      render();
    }
    function setMomentum(value) {
      state.momentumMevC = clampMomentum(value);
      if (el.inputMomentum) el.inputMomentum.value = String(state.momentumMevC);
      if (el.outMomentum) el.outMomentum.textContent = String(state.momentumMevC);
      recompute();
      render();
    }
    function reset() {
      setRestEnergy(105.66);
      setMomentum(200);
    }

    function renderScene() {
      var baseX = 40, maxX = 340;
      var trailLen = computed.velocityFractionC * (maxX - baseX);
      if (el.trail) {
        el.trail.setAttribute("x1", String(baseX));
        el.trail.setAttribute("x2", String(baseX + trailLen));
      }
      if (el.particle) {
        el.particle.setAttribute("cx", String(baseX + trailLen));
      }
      var text =
        "A particle with rest energy " + computed.restEnergyMev.toFixed(2) + " mega-electronvolts and momentum " +
        computed.momentumMevC.toFixed(2) + " MeV/c has total energy " + computed.totalEnergyMev.toFixed(2) +
        " MeV and travels at " + (computed.velocityFractionC * 100).toFixed(1) + " percent of the speed of light.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
      if (el.sceneStatus) el.sceneStatus.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 50, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var samples = 60;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var pc = (MAX_MOMENTUM_MEV_C * i) / samples;
        var e = Math.sqrt(pc * pc + state.restEnergyMev * state.restEnergyMev);
        var beta = pc / e;
        var px = left + (pc / MAX_MOMENTUM_MEV_C) * plotW;
        var py = top + plotH - beta * plotH;
        points.push(px.toFixed(1) + "," + py.toFixed(1));
      }
      el.curve.setAttribute("points", points.join(" "));
      if (el.marker) {
        var mx = left + (computed.momentumMevC / MAX_MOMENTUM_MEV_C) * plotW;
        var my = top + plotH - computed.velocityFractionC * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "A graph of speed, as a fraction of the speed of light, against momentum for this particle's rest energy. " +
        "It rises quickly at low momentum and flattens out, approaching but never reaching the speed of light.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueRestEnergy) el.valueRestEnergy.textContent = state.restEnergyMev.toFixed(2);
      if (el.valueMomentum) el.valueMomentum.textContent = state.momentumMevC.toFixed(2);
      if (el.valueTotalEnergy) el.valueTotalEnergy.textContent = computed.totalEnergyMev.toFixed(2);
      if (el.valueKineticEnergy) el.valueKineticEnergy.textContent = computed.kineticEnergyMev.toFixed(2);
      if (el.valueBeta) el.valueBeta.textContent = computed.velocityFractionC.toFixed(3);
      if (el.eqTotalEnergy) el.eqTotalEnergy.textContent = computed.totalEnergyMev.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        restEnergyMev: state.restEnergyMev,
        momentumMevC: state.momentumMevC,
        totalEnergyMev: computed.totalEnergyMev,
        kineticEnergyMev: computed.kineticEnergyMev,
        velocityFractionC: computed.velocityFractionC,
        running: false
      };
    }

    if (el.inputRestEnergy) {
      el.inputRestEnergy.addEventListener("input", function () { setRestEnergy(el.inputRestEnergy.value); });
      el.inputRestEnergy.addEventListener("change", function () { setRestEnergy(el.inputRestEnergy.value); });
    }
    if (el.inputMomentum) {
      el.inputMomentum.addEventListener("input", function () { setMomentum(el.inputMomentum.value); });
      el.inputMomentum.addEventListener("change", function () { setMomentum(el.inputMomentum.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setRestEnergy: setRestEnergy,
      setMomentum: setMomentum,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("particle_physics", createParticlePhysicsSim);

  PhysicsLab.ParticlePhysics = {
    MIN_REST_ENERGY_MEV: MIN_REST_ENERGY_MEV,
    MAX_REST_ENERGY_MEV: MAX_REST_ENERGY_MEV,
    MIN_MOMENTUM_MEV_C: MIN_MOMENTUM_MEV_C,
    MAX_MOMENTUM_MEV_C: MAX_MOMENTUM_MEV_C,
    clampRestEnergy: clampRestEnergy,
    clampMomentum: clampMomentum,
    computeState: computeState
  };
})(window, document);
