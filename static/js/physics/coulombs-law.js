/**
 * Coulomb's Law simulation.
 *
 * Two point charges, q1 and q2 (signed, microcoulombs), separated by a
 * fixed distance r:
 *
 * F = k |q1 q2| / r^2   (force magnitude, always >= 0)
 * U = k q1 q2 / r       (potential energy -- signed: negative = attraction,
 *                        positive = repulsion)
 * E1_at_2 = k |q1| / r^2, E2_at_1 = k |q2| / r^2
 *
 * Attractive when the charges have opposite signs, repulsive when they
 * have the same sign -- unlike gravity (Orbital Motion), which is always
 * attractive. Like circuits.js, there is no time axis and no run loop:
 * values are recomputed live on every control change. Always computed
 * here, in code -- never fetched from a server and never generated by AI.
 * Mirrors apps/physics/simulations_coulombs_law.py exactly (same bounds,
 * same formulas, same Coulomb's constant). This file owns its own physics,
 * SVG and controls; it shares only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var COULOMB_K = 8.99e9;
  var MIN_CHARGE_UC = -8.0;
  var MAX_CHARGE_UC = 8.0;
  var MIN_SEPARATION_M = 0.1;
  var MAX_SEPARATION_M = 5.0;

  function clampCharge(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_CHARGE_UC, Math.min(MAX_CHARGE_UC, n));
  }
  function clampSeparation(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_SEPARATION_M, Math.min(MAX_SEPARATION_M, n));
  }

  function computeState(charge1, charge2, separation) {
    var q1uc = clampCharge(charge1);
    var q2uc = clampCharge(charge2);
    var r = clampSeparation(separation);
    var q1 = q1uc * 1e-6;
    var q2 = q2uc * 1e-6;

    var force = (COULOMB_K * Math.abs(q1 * q2)) / (r * r);
    var potentialEnergy = (COULOMB_K * q1 * q2) / r;
    var isAttractive = q1 * q2 < 0;
    var field1At2 = (COULOMB_K * Math.abs(q1)) / (r * r);
    var field2At1 = (COULOMB_K * Math.abs(q2)) / (r * r);

    return {
      charge1: q1uc,
      charge2: q2uc,
      separation: r,
      force: force,
      isAttractive: isAttractive,
      potentialEnergy: potentialEnergy,
      field1At2: field1At2,
      field2At1: field2At1
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createCoulombSim(root, config, lab) {
    var state = {
      charge1: clampCharge(readNum(root, "charge1", 3)),
      charge2: clampCharge(readNum(root, "charge2", -2)),
      separation: clampSeparation(readNum(root, "separation", 1))
    };
    var computed = computeState(state.charge1, state.charge2, state.separation);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      chargeA: root.querySelector("[data-charge-a]"),
      chargeB: root.querySelector("[data-charge-b]"),
      forceArrowLeft: root.querySelector("[data-force-arrow-left]"),
      forceArrowRight: root.querySelector("[data-force-arrow-right]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueCharge1: root.querySelector("[data-value-charge1]"),
      valueCharge2: root.querySelector("[data-value-charge2]"),
      valueSeparation: root.querySelector("[data-value-separation]"),
      valueForce: root.querySelector("[data-value-force]"),
      valueInteraction: root.querySelector("[data-value-interaction]"),
      valuePe: root.querySelector("[data-value-pe]"),
      eqForce: root.querySelector("[data-eq-force]"),
      eqPe: root.querySelector("[data-eq-pe]"),
      outCharge1: root.querySelector("[data-out-charge1]"),
      outCharge2: root.querySelector("[data-out-charge2]"),
      outSeparation: root.querySelector("[data-out-separation]"),
      inputCharge1: root.querySelector("[data-input-charge1]"),
      inputCharge2: root.querySelector("[data-input-charge2]"),
      inputSeparation: root.querySelector("[data-input-separation]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.charge1, state.charge2, state.separation);
    }

    function setCharge1(value) {
      state.charge1 = clampCharge(value);
      if (el.inputCharge1) el.inputCharge1.value = String(state.charge1);
      if (el.outCharge1) el.outCharge1.textContent = String(state.charge1);
      recompute();
      render();
    }
    function setCharge2(value) {
      state.charge2 = clampCharge(value);
      if (el.inputCharge2) el.inputCharge2.value = String(state.charge2);
      if (el.outCharge2) el.outCharge2.textContent = String(state.charge2);
      recompute();
      render();
    }
    function setSeparation(value) {
      state.separation = clampSeparation(value);
      if (el.inputSeparation) el.inputSeparation.value = String(state.separation);
      if (el.outSeparation) el.outSeparation.textContent = String(state.separation);
      recompute();
      render();
    }
    function reset() {
      setCharge1(3);
      setCharge2(-2);
      setSeparation(1);
    }

    function renderScene() {
      var span = 320;
      var leftX = 40 + (span - span * (state.separation / MAX_SEPARATION_M)) / 2;
      var rightX = leftX + span * (state.separation / MAX_SEPARATION_M);
      if (el.chargeA) {
        el.chargeA.setAttribute("cx", leftX.toFixed(1));
        el.chargeA.setAttribute("fill", state.charge1 > 0 ? "#e0575b" : state.charge1 < 0 ? "#4fa8e0" : "#6b7785");
      }
      if (el.chargeB) {
        el.chargeB.setAttribute("cx", rightX.toFixed(1));
        el.chargeB.setAttribute("fill", state.charge2 > 0 ? "#e0575b" : state.charge2 < 0 ? "#4fa8e0" : "#6b7785");
      }
      var midX = (leftX + rightX) / 2;
      var gap = 18;
      if (el.forceArrowLeft) {
        if (computed.isAttractive) {
          el.forceArrowLeft.setAttribute("x1", (leftX + gap).toFixed(1));
          el.forceArrowLeft.setAttribute("x2", (midX - 4).toFixed(1));
        } else {
          el.forceArrowLeft.setAttribute("x1", (leftX - gap).toFixed(1));
          el.forceArrowLeft.setAttribute("x2", (leftX - gap - 22).toFixed(1));
        }
      }
      if (el.forceArrowRight) {
        if (computed.isAttractive) {
          el.forceArrowRight.setAttribute("x1", (rightX - gap).toFixed(1));
          el.forceArrowRight.setAttribute("x2", (midX + 4).toFixed(1));
        } else {
          el.forceArrowRight.setAttribute("x1", (rightX + gap).toFixed(1));
          el.forceArrowRight.setAttribute("x2", (rightX + gap + 22).toFixed(1));
        }
      }
      var interactionWord = computed.force === 0 ? "zero" : (computed.isAttractive ? "attractive" : "repulsive");
      var text =
        "Two charges, " + state.charge1.toFixed(1) + " and " + state.charge2.toFixed(1) +
        " microcoulombs, " + state.separation.toFixed(2) + " metres apart. The force between " +
        "them is " + interactionWord + ", " + computed.force.toFixed(4) + " newtons.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var samples = 40;
      var maxF = 0;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var r = MIN_SEPARATION_M + ((MAX_SEPARATION_M - MIN_SEPARATION_M) * i) / samples;
        var c = computeState(state.charge1, state.charge2, r);
        points.push([r, c.force]);
        if (c.force > maxF) maxF = c.force;
      }
      maxF = Math.max(maxF, 1e-9);
      var path = points.map(function (p, i) {
        var px = left + ((p[0] - MIN_SEPARATION_M) / (MAX_SEPARATION_M - MIN_SEPARATION_M)) * plotW;
        var py = top + plotH - (p[1] / maxF) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        var mx = left + ((state.separation - MIN_SEPARATION_M) / (MAX_SEPARATION_M - MIN_SEPARATION_M)) * plotW;
        var my = top + plotH - (computed.force / maxF) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "Force versus separation, for these two charges. Force falls off with the " +
        "square of the distance. At the current separation of " + state.separation.toFixed(2) +
        " metres, the force is " + computed.force.toFixed(4) + " newtons.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueCharge1) el.valueCharge1.textContent = state.charge1.toFixed(1);
      if (el.valueCharge2) el.valueCharge2.textContent = state.charge2.toFixed(1);
      if (el.valueSeparation) el.valueSeparation.textContent = state.separation.toFixed(2);
      if (el.valueForce) el.valueForce.textContent = computed.force.toFixed(4);
      if (el.valueInteraction) {
        el.valueInteraction.textContent =
          computed.force === 0 ? "No force" : (computed.isAttractive ? "Attractive" : "Repulsive");
      }
      if (el.valuePe) el.valuePe.textContent = computed.potentialEnergy.toFixed(6);
      if (el.eqForce) el.eqForce.textContent = computed.force.toFixed(4);
      if (el.eqPe) el.eqPe.textContent = computed.potentialEnergy.toFixed(6);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        charge1Uc: state.charge1,
        charge2Uc: state.charge2,
        separationM: state.separation,
        forceN: computed.force,
        isAttractive: computed.isAttractive ? 1 : 0,
        potentialEnergyJ: computed.potentialEnergy,
        running: false
      };
    }

    if (el.inputCharge1) {
      el.inputCharge1.addEventListener("input", function () { setCharge1(el.inputCharge1.value); });
      el.inputCharge1.addEventListener("change", function () { setCharge1(el.inputCharge1.value); });
    }
    if (el.inputCharge2) {
      el.inputCharge2.addEventListener("input", function () { setCharge2(el.inputCharge2.value); });
      el.inputCharge2.addEventListener("change", function () { setCharge2(el.inputCharge2.value); });
    }
    if (el.inputSeparation) {
      el.inputSeparation.addEventListener("input", function () { setSeparation(el.inputSeparation.value); });
      el.inputSeparation.addEventListener("change", function () { setSeparation(el.inputSeparation.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setCharge1: setCharge1,
      setCharge2: setCharge2,
      setSeparation: setSeparation,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("coulombs_law", createCoulombSim);

  PhysicsLab.CoulombsLaw = {
    COULOMB_K: COULOMB_K,
    MIN_CHARGE_UC: MIN_CHARGE_UC,
    MAX_CHARGE_UC: MAX_CHARGE_UC,
    MIN_SEPARATION_M: MIN_SEPARATION_M,
    MAX_SEPARATION_M: MAX_SEPARATION_M,
    clampCharge: clampCharge,
    clampSeparation: clampSeparation,
    computeState: computeState
  };
})(window, document);
