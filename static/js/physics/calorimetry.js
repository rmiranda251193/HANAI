/**
 * Calorimetry simulation.
 *
 * C1 = mass1 * specificHeat1, C2 = mass2 * specificHeat2   (heat capacity)
 * T_eq = (C1*temp1 + C2*temp2) / (C1 + C2)                 (equilibrium)
 * heatTransferred = |C1 * (temp1 - T_eq)| = |C2 * (T_eq - temp2)|
 *
 * Unlike buoyancy.js (floats/sinks) or refraction.js (refracts/TIR), this
 * formula has no branching case at all -- it works the same way regardless
 * of which substance starts warmer. Like circuits.js/coulombs-law.js/
 * buoyancy.js/refraction.js, there is no time axis and no run loop: values
 * are recomputed live on every control change. Always computed here, in
 * code -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_calorimetry.py exactly (same bounds, same
 * formulas). This file owns its own physics, SVG and controls; it shares
 * only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_MASS_KG = 0.01;
  var MAX_MASS_KG = 10.0;
  var MIN_SPECIFIC_HEAT = 100.0;
  var MAX_SPECIFIC_HEAT = 4200.0;
  var MIN_TEMP_C = -20.0;
  var MAX_TEMP_C = 300.0;

  function clampMass(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_MASS_KG, Math.min(MAX_MASS_KG, n));
  }
  function clampSpecificHeat(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_SPECIFIC_HEAT, Math.min(MAX_SPECIFIC_HEAT, n));
  }
  function clampTemp(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_TEMP_C, Math.min(MAX_TEMP_C, n));
  }

  function computeState(mass1, specificHeat1, temp1, mass2, specificHeat2, temp2) {
    var m1 = clampMass(mass1);
    var c1 = clampSpecificHeat(specificHeat1);
    var t1 = clampTemp(temp1);
    var m2 = clampMass(mass2);
    var c2 = clampSpecificHeat(specificHeat2);
    var t2 = clampTemp(temp2);

    var heatCapacity1 = m1 * c1;
    var heatCapacity2 = m2 * c2;
    var equilibriumTemp = (heatCapacity1 * t1 + heatCapacity2 * t2) / (heatCapacity1 + heatCapacity2);
    var heatTransferred = Math.abs(heatCapacity1 * (t1 - equilibriumTemp));

    return {
      mass1: m1, specificHeat1: c1, temp1: t1,
      mass2: m2, specificHeat2: c2, temp2: t2,
      heatCapacity1: heatCapacity1,
      heatCapacity2: heatCapacity2,
      equilibriumTemp: equilibriumTemp,
      heatTransferred: heatTransferred
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createCalorimetrySim(root, config, lab) {
    var state = {
      mass1: clampMass(readNum(root, "mass1", 0.5)),
      specificHeat1: clampSpecificHeat(readNum(root, "specific-heat1", 4186)),
      temp1: clampTemp(readNum(root, "temp1", 20)),
      mass2: clampMass(readNum(root, "mass2", 0.2)),
      specificHeat2: clampSpecificHeat(readNum(root, "specific-heat2", 900)),
      temp2: clampTemp(readNum(root, "temp2", 100))
    };
    var computed = computeState(
      state.mass1, state.specificHeat1, state.temp1,
      state.mass2, state.specificHeat2, state.temp2
    );

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      bar1: root.querySelector("[data-bar-temp1]"),
      bar2: root.querySelector("[data-bar-temp2]"),
      eqLine: root.querySelector("[data-eq-line]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      barC1: root.querySelector("[data-bar-c1]"),
      barC2: root.querySelector("[data-bar-c2]"),
      barC1Label: root.querySelector("[data-bar-c1-label]"),
      barC2Label: root.querySelector("[data-bar-c2-label]"),
      valueMass1: root.querySelector("[data-value-mass1]"),
      valueMass2: root.querySelector("[data-value-mass2]"),
      valueTemp1: root.querySelector("[data-value-temp1]"),
      valueTemp2: root.querySelector("[data-value-temp2]"),
      valueEq: root.querySelector("[data-value-eq]"),
      valueHeat: root.querySelector("[data-value-heat]"),
      eqEq: root.querySelector("[data-eq-eq]"),
      outMass1: root.querySelector("[data-out-mass1]"),
      outHeat1: root.querySelector("[data-out-specific-heat1]"),
      outTemp1: root.querySelector("[data-out-temp1]"),
      outMass2: root.querySelector("[data-out-mass2]"),
      outHeat2: root.querySelector("[data-out-specific-heat2]"),
      outTemp2: root.querySelector("[data-out-temp2]"),
      inputMass1: root.querySelector("[data-input-mass1]"),
      inputHeat1: root.querySelector("[data-input-specific-heat1]"),
      inputTemp1: root.querySelector("[data-input-temp1]"),
      inputMass2: root.querySelector("[data-input-mass2]"),
      inputHeat2: root.querySelector("[data-input-specific-heat2]"),
      inputTemp2: root.querySelector("[data-input-temp2]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(
        state.mass1, state.specificHeat1, state.temp1,
        state.mass2, state.specificHeat2, state.temp2
      );
    }

    function makeSetter(key, clampFn, inputEl, outEl) {
      return function (value) {
        state[key] = clampFn(value);
        if (inputEl) inputEl.value = String(state[key]);
        if (outEl) outEl.textContent = String(state[key]);
        recompute();
        render();
      };
    }

    var setMass1 = makeSetter("mass1", clampMass, el.inputMass1, el.outMass1);
    var setHeat1 = makeSetter("specificHeat1", clampSpecificHeat, el.inputHeat1, el.outHeat1);
    var setTemp1 = makeSetter("temp1", clampTemp, el.inputTemp1, el.outTemp1);
    var setMass2 = makeSetter("mass2", clampMass, el.inputMass2, el.outMass2);
    var setHeat2 = makeSetter("specificHeat2", clampSpecificHeat, el.inputHeat2, el.outHeat2);
    var setTemp2 = makeSetter("temp2", clampTemp, el.inputTemp2, el.outTemp2);

    function reset() {
      setMass1(0.5);
      setHeat1(4186);
      setTemp1(20);
      setMass2(0.2);
      setHeat2(900);
      setTemp2(100);
    }

    function tempToY(tempC) {
      var frac = (tempC - MIN_TEMP_C) / (MAX_TEMP_C - MIN_TEMP_C);
      return 190 - frac * 150; // 190 (cold, bottom) .. 40 (hot, top)
    }

    function renderScene() {
      var y1 = tempToY(state.temp1);
      var y2 = tempToY(state.temp2);
      var yEq = tempToY(computed.equilibriumTemp);
      if (el.bar1) {
        el.bar1.setAttribute("y", String(y1));
        el.bar1.setAttribute("height", String(190 - y1));
      }
      if (el.bar2) {
        el.bar2.setAttribute("y", String(y2));
        el.bar2.setAttribute("height", String(190 - y2));
      }
      if (el.eqLine) {
        el.eqLine.setAttribute("y1", yEq.toFixed(1));
        el.eqLine.setAttribute("y2", yEq.toFixed(1));
      }
      var text =
        "Substance 1 starts at " + state.temp1.toFixed(0) + " degrees, substance 2 at " +
        state.temp2.toFixed(0) + " degrees. Mixed together, both settle at " +
        computed.equilibriumTemp.toFixed(1) + " degrees.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.barC1 || !el.barC2) return;
      var maxC = Math.max(1e-9, computed.heatCapacity1, computed.heatCapacity2);
      var baseY = 150, maxBarH = 120;
      var h1 = (computed.heatCapacity1 / maxC) * maxBarH;
      var h2 = (computed.heatCapacity2 / maxC) * maxBarH;
      el.barC1.setAttribute("y", String(baseY - h1));
      el.barC1.setAttribute("height", String(h1));
      el.barC2.setAttribute("y", String(baseY - h2));
      el.barC2.setAttribute("height", String(h2));
      if (el.barC1Label) {
        el.barC1Label.setAttribute("y", String(baseY - h1 - 6));
        el.barC1Label.textContent = computed.heatCapacity1.toFixed(0) + " J/K";
      }
      if (el.barC2Label) {
        el.barC2Label.setAttribute("y", String(baseY - h2 - 6));
        el.barC2Label.textContent = computed.heatCapacity2.toFixed(0) + " J/K";
      }
      var graphText =
        "Comparing heat capacity: substance 1 has " + computed.heatCapacity1.toFixed(0) +
        " joules per kelvin, substance 2 has " + computed.heatCapacity2.toFixed(0) +
        " joules per kelvin. The equilibrium temperature lands closer to whichever substance's bar is taller.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueMass1) el.valueMass1.textContent = state.mass1.toFixed(2);
      if (el.valueMass2) el.valueMass2.textContent = state.mass2.toFixed(2);
      if (el.valueTemp1) el.valueTemp1.textContent = state.temp1.toFixed(1);
      if (el.valueTemp2) el.valueTemp2.textContent = state.temp2.toFixed(1);
      if (el.valueEq) el.valueEq.textContent = computed.equilibriumTemp.toFixed(1);
      if (el.valueHeat) el.valueHeat.textContent = computed.heatTransferred.toFixed(1);
      if (el.eqEq) el.eqEq.textContent = computed.equilibriumTemp.toFixed(1);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        mass1Kg: state.mass1,
        specificHeat1: state.specificHeat1,
        temp1C: state.temp1,
        mass2Kg: state.mass2,
        specificHeat2: state.specificHeat2,
        temp2C: state.temp2,
        equilibriumTempC: computed.equilibriumTemp,
        heatTransferredJ: computed.heatTransferred,
        running: false
      };
    }

    if (el.inputMass1) {
      el.inputMass1.addEventListener("input", function () { setMass1(el.inputMass1.value); });
      el.inputMass1.addEventListener("change", function () { setMass1(el.inputMass1.value); });
    }
    if (el.inputHeat1) {
      el.inputHeat1.addEventListener("input", function () { setHeat1(el.inputHeat1.value); });
      el.inputHeat1.addEventListener("change", function () { setHeat1(el.inputHeat1.value); });
    }
    if (el.inputTemp1) {
      el.inputTemp1.addEventListener("input", function () { setTemp1(el.inputTemp1.value); });
      el.inputTemp1.addEventListener("change", function () { setTemp1(el.inputTemp1.value); });
    }
    if (el.inputMass2) {
      el.inputMass2.addEventListener("input", function () { setMass2(el.inputMass2.value); });
      el.inputMass2.addEventListener("change", function () { setMass2(el.inputMass2.value); });
    }
    if (el.inputHeat2) {
      el.inputHeat2.addEventListener("input", function () { setHeat2(el.inputHeat2.value); });
      el.inputHeat2.addEventListener("change", function () { setHeat2(el.inputHeat2.value); });
    }
    if (el.inputTemp2) {
      el.inputTemp2.addEventListener("input", function () { setTemp2(el.inputTemp2.value); });
      el.inputTemp2.addEventListener("change", function () { setTemp2(el.inputTemp2.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setMass1: setMass1,
      setSpecificHeat1: setHeat1,
      setTemp1: setTemp1,
      setMass2: setMass2,
      setSpecificHeat2: setHeat2,
      setTemp2: setTemp2,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("calorimetry", createCalorimetrySim);

  PhysicsLab.Calorimetry = {
    MIN_MASS_KG: MIN_MASS_KG,
    MAX_MASS_KG: MAX_MASS_KG,
    MIN_SPECIFIC_HEAT: MIN_SPECIFIC_HEAT,
    MAX_SPECIFIC_HEAT: MAX_SPECIFIC_HEAT,
    MIN_TEMP_C: MIN_TEMP_C,
    MAX_TEMP_C: MAX_TEMP_C,
    clampMass: clampMass,
    clampSpecificHeat: clampSpecificHeat,
    clampTemp: clampTemp,
    computeState: computeState
  };
})(window, document);
