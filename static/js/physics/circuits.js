/**
 * Series and Parallel Circuits simulation.
 *
 * An ideal voltage source wired to two resistors, either in series or in
 * parallel:
 *
 * series:   R = R1 + R2,  I = V / R                 (same current, V splits)
 * parallel: 1/R = 1/R1 + 1/R2,  I1 = V/R1, I2 = V/R2 (same voltage, I splits)
 * always:   P = V * I = P1 + P2
 *
 * Unlike every other simulation in this lab, there is no time axis and no
 * run loop -- with an ideal source and ideal wires the circuit reaches its
 * steady state the instant the switch closes, so values are recomputed live
 * on every control change instead of animating. Always computed here, in
 * code -- never fetched from a server and never generated by AI. Mirrors
 * apps/physics/simulations_circuits.py exactly (same bounds, same
 * formulas). This file owns its own physics, SVG and controls; it shares
 * only the registry shell in lab.js (no run loop is used).
 */
(function (window, document) {
  "use strict";

  var MIN_VOLTAGE_V = 1.0;
  var MAX_VOLTAGE_V = 24.0;
  var MIN_RESISTANCE_OHM = 1.0;
  var MAX_RESISTANCE_OHM = 100.0;

  function clampVoltage(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_VOLTAGE_V, Math.min(MAX_VOLTAGE_V, n));
  }
  function clampResistance(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_RESISTANCE_OHM, Math.min(MAX_RESISTANCE_OHM, n));
  }
  function clampSeries(value) {
    var n = Number(value);
    if (!isFinite(n)) return 1;
    return n >= 0.5 ? 1 : 0;
  }

  function computeState(voltage, r1, r2, seriesFlag) {
    var v = clampVoltage(voltage);
    var ra = clampResistance(r1);
    var rb = clampResistance(r2);
    var isSeries = clampSeries(seriesFlag) === 1;

    var seriesTotalR = ra + rb;
    var parallelTotalR = (ra * rb) / (ra + rb);

    var totalR, totalI, i1, i2, v1, v2;
    if (isSeries) {
      totalR = seriesTotalR;
      totalI = v / totalR;
      i1 = totalI;
      i2 = totalI;
      v1 = i1 * ra;
      v2 = i2 * rb;
    } else {
      totalR = parallelTotalR;
      totalI = v / totalR;
      v1 = v;
      v2 = v;
      i1 = v1 / ra;
      i2 = v2 / rb;
    }
    var p1 = i1 * v1;
    var p2 = i2 * v2;
    var totalP = p1 + p2;

    return {
      voltage: v,
      r1: ra,
      r2: rb,
      series: isSeries,
      totalR: totalR,
      totalI: totalI,
      i1: i1,
      i2: i2,
      v1: v1,
      v2: v2,
      p1: p1,
      p2: p2,
      totalP: totalP,
      seriesTotalR: seriesTotalR,
      parallelTotalR: parallelTotalR
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createCircuitSim(root, config, lab) {
    var state = {
      voltage: clampVoltage(readNum(root, "voltage", 12)),
      r1: clampResistance(readNum(root, "r1", 10)),
      r2: clampResistance(readNum(root, "r2", 20)),
      series: clampSeries(readNum(root, "series", 1)) === 1
    };
    var computed = computeState(state.voltage, state.r1, state.r2, state.series ? 1 : 0);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      seriesDiagram: root.querySelector("[data-series-diagram]"),
      parallelDiagram: root.querySelector("[data-parallel-diagram]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      barSeries: root.querySelector("[data-bar-series]"),
      barParallel: root.querySelector("[data-bar-parallel]"),
      barSeriesLabel: root.querySelector("[data-bar-series-label]"),
      barParallelLabel: root.querySelector("[data-bar-parallel-label]"),
      valueVoltage: root.querySelector("[data-value-voltage]"),
      valueR1: root.querySelector("[data-value-r1]"),
      valueR2: root.querySelector("[data-value-r2]"),
      valueTotalR: root.querySelector("[data-value-total-r]"),
      valueTotalI: root.querySelector("[data-value-total-i]"),
      valueI1: root.querySelector("[data-value-i1]"),
      valueI2: root.querySelector("[data-value-i2]"),
      valueV1: root.querySelector("[data-value-v1]"),
      valueV2: root.querySelector("[data-value-v2]"),
      valueTotalP: root.querySelector("[data-value-total-p]"),
      eqTotalI: root.querySelector("[data-eq-total-i]"),
      eqTotalP: root.querySelector("[data-eq-total-p]"),
      outVoltage: root.querySelector("[data-out-voltage]"),
      outR1: root.querySelector("[data-out-r1]"),
      outR2: root.querySelector("[data-out-r2]"),
      inputVoltage: root.querySelector("[data-input-voltage]"),
      inputR1: root.querySelector("[data-input-r1]"),
      inputR2: root.querySelector("[data-input-r2]"),
      inputSeries: root.querySelectorAll("[data-input-series]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.voltage, state.r1, state.r2, state.series ? 1 : 0);
    }

    function setVoltage(value) {
      state.voltage = clampVoltage(value);
      if (el.inputVoltage) el.inputVoltage.value = String(state.voltage);
      if (el.outVoltage) el.outVoltage.textContent = String(state.voltage);
      recompute();
      render();
    }
    function setR1(value) {
      state.r1 = clampResistance(value);
      if (el.inputR1) el.inputR1.value = String(state.r1);
      if (el.outR1) el.outR1.textContent = String(state.r1);
      recompute();
      render();
    }
    function setR2(value) {
      state.r2 = clampResistance(value);
      if (el.inputR2) el.inputR2.value = String(state.r2);
      if (el.outR2) el.outR2.textContent = String(state.r2);
      recompute();
      render();
    }
    function setSeries(value) {
      state.series = clampSeries(value) === 1;
      for (var i = 0; i < el.inputSeries.length; i++) {
        el.inputSeries[i].checked = (el.inputSeries[i].value === (state.series ? "1" : "0"));
      }
      recompute();
      render();
    }
    function reset() {
      setVoltage(12);
      setR1(10);
      setR2(20);
      setSeries(1);
    }

    function renderScene() {
      if (el.seriesDiagram) el.seriesDiagram.hidden = !state.series;
      if (el.parallelDiagram) el.parallelDiagram.hidden = state.series;
      var text =
        "A " + state.voltage.toFixed(1) + " volt source wired to two resistors, " +
        state.r1.toFixed(0) + " ohms and " + state.r2.toFixed(0) + " ohms, in " +
        (state.series ? "series" : "parallel") + ". Total current drawn: " +
        computed.totalI.toFixed(2) + " amps.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.barSeries || !el.barParallel) return;
      var maxR = Math.max(1, computed.seriesTotalR, computed.parallelTotalR);
      var chartH = 130, baseY = 150, maxBarH = 120;
      var seriesH = (computed.seriesTotalR / maxR) * maxBarH;
      var parallelH = (computed.parallelTotalR / maxR) * maxBarH;
      el.barSeries.setAttribute("y", String(baseY - seriesH));
      el.barSeries.setAttribute("height", String(seriesH));
      el.barParallel.setAttribute("y", String(baseY - parallelH));
      el.barParallel.setAttribute("height", String(parallelH));
      if (el.barSeriesLabel) {
        el.barSeriesLabel.setAttribute("y", String(baseY - seriesH - 6));
        el.barSeriesLabel.textContent = computed.seriesTotalR.toFixed(1) + " Ω";
      }
      if (el.barParallelLabel) {
        el.barParallelLabel.setAttribute("y", String(baseY - parallelH - 6));
        el.barParallelLabel.textContent = computed.parallelTotalR.toFixed(1) + " Ω";
      }
      var graphText =
        "Comparing total resistance: " + computed.seriesTotalR.toFixed(1) +
        " ohms in series versus " + computed.parallelTotalR.toFixed(1) +
        " ohms in parallel -- the parallel combination is always smaller " +
        "than either resistor alone.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
      void chartH;
    }

    function render() {
      if (el.valueVoltage) el.valueVoltage.textContent = state.voltage.toFixed(1);
      if (el.valueR1) el.valueR1.textContent = state.r1.toFixed(0);
      if (el.valueR2) el.valueR2.textContent = state.r2.toFixed(0);
      if (el.valueTotalR) el.valueTotalR.textContent = computed.totalR.toFixed(2);
      if (el.valueTotalI) el.valueTotalI.textContent = computed.totalI.toFixed(2);
      if (el.valueI1) el.valueI1.textContent = computed.i1.toFixed(2);
      if (el.valueI2) el.valueI2.textContent = computed.i2.toFixed(2);
      if (el.valueV1) el.valueV1.textContent = computed.v1.toFixed(2);
      if (el.valueV2) el.valueV2.textContent = computed.v2.toFixed(2);
      if (el.valueTotalP) el.valueTotalP.textContent = computed.totalP.toFixed(2);
      if (el.eqTotalI) el.eqTotalI.textContent = computed.totalI.toFixed(2);
      if (el.eqTotalP) el.eqTotalP.textContent = computed.totalP.toFixed(2);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        voltageV: state.voltage,
        resistance1Ohm: state.r1,
        resistance2Ohm: state.r2,
        series: state.series ? 1 : 0,
        totalResistanceOhm: computed.totalR,
        totalCurrentA: computed.totalI,
        current1A: computed.i1,
        current2A: computed.i2,
        voltage1V: computed.v1,
        voltage2V: computed.v2,
        totalPowerW: computed.totalP,
        running: false
      };
    }

    if (el.inputVoltage) {
      el.inputVoltage.addEventListener("input", function () { setVoltage(el.inputVoltage.value); });
      el.inputVoltage.addEventListener("change", function () { setVoltage(el.inputVoltage.value); });
    }
    if (el.inputR1) {
      el.inputR1.addEventListener("input", function () { setR1(el.inputR1.value); });
      el.inputR1.addEventListener("change", function () { setR1(el.inputR1.value); });
    }
    if (el.inputR2) {
      el.inputR2.addEventListener("input", function () { setR2(el.inputR2.value); });
      el.inputR2.addEventListener("change", function () { setR2(el.inputR2.value); });
    }
    for (var s = 0; s < el.inputSeries.length; s++) {
      (function (radio) {
        radio.addEventListener("change", function () {
          if (radio.checked) setSeries(radio.value);
        });
      })(el.inputSeries[s]);
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setVoltage: setVoltage,
      setR1: setR1,
      setR2: setR2,
      setSeries: setSeries,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("series_parallel_circuit", createCircuitSim);

  PhysicsLab.Circuits = {
    MIN_VOLTAGE_V: MIN_VOLTAGE_V,
    MAX_VOLTAGE_V: MAX_VOLTAGE_V,
    MIN_RESISTANCE_OHM: MIN_RESISTANCE_OHM,
    MAX_RESISTANCE_OHM: MAX_RESISTANCE_OHM,
    clampVoltage: clampVoltage,
    clampResistance: clampResistance,
    clampSeries: clampSeries,
    computeState: computeState
  };
})(window, document);
