/**
 * Time Dilation and Length Contraction simulation.
 *
 * gamma = 1 / sqrt(1 - beta^2)        (beta = v/c, the Lorentz factor)
 * dilatedTime = properTime * gamma     (always longer than proper time)
 * contractedLength = properLength / gamma   (always shorter than proper length)
 *
 * One factor, two companion effects -- no branching case. Like
 * circuits.js/coulombs-law.js/buoyancy.js/refraction.js/calorimetry.js/
 * ideal-gas-law.js/doppler-effect.js, there is no time axis (in the
 * animation sense) and no run loop: values are recomputed live on every
 * control change. Always computed here, in code -- never fetched from a
 * server and never generated by AI. Mirrors
 * apps/physics/simulations_time_dilation.py exactly (same bounds, same
 * formulas). This file owns its own physics, SVG and controls; it shares
 * only the registry shell in lab.js.
 */
(function (window, document) {
  "use strict";

  var MIN_VELOCITY_FRACTION_C = 0.0;
  var MAX_VELOCITY_FRACTION_C = 0.99;
  var MIN_PROPER_TIME_S = 0.1;
  var MAX_PROPER_TIME_S = 100.0;
  var MIN_PROPER_LENGTH_M = 0.1;
  var MAX_PROPER_LENGTH_M = 1000.0;

  function clampVelocityFraction(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_VELOCITY_FRACTION_C, Math.min(MAX_VELOCITY_FRACTION_C, n));
  }
  function clampProperTime(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_PROPER_TIME_S, Math.min(MAX_PROPER_TIME_S, n));
  }
  function clampProperLength(value) {
    var n = Number(value);
    if (!isFinite(n)) return NaN;
    return Math.max(MIN_PROPER_LENGTH_M, Math.min(MAX_PROPER_LENGTH_M, n));
  }

  function computeState(velocityFractionC, properTime, properLength) {
    var beta = clampVelocityFraction(velocityFractionC);
    var t0 = clampProperTime(properTime);
    var l0 = clampProperLength(properLength);
    var gamma = 1 / Math.sqrt(1 - beta * beta);
    var dilatedTime = t0 * gamma;
    var contractedLength = l0 / gamma;
    return {
      beta: beta,
      properTime: t0,
      properLength: l0,
      gamma: gamma,
      dilatedTime: dilatedTime,
      contractedLength: contractedLength
    };
  }

  function readNum(el, name, fallback) {
    var raw = el.getAttribute("data-" + name);
    var value = parseFloat(raw);
    return isFinite(value) ? value : fallback;
  }

  function createTimeDilationSim(root, config, lab) {
    var state = {
      beta: clampVelocityFraction(readNum(root, "velocity-fraction", 0.6)),
      properTime: clampProperTime(readNum(root, "proper-time", 10)),
      properLength: clampProperLength(readNum(root, "proper-length", 100))
    };
    var computed = computeState(state.beta, state.properTime, state.properLength);

    var el = {
      scene: root.querySelector("[data-lab-scene]"),
      sceneDesc: root.querySelector("[data-scene-desc]"),
      barProper: root.querySelector("[data-bar-proper]"),
      barContracted: root.querySelector("[data-bar-contracted]"),
      barProperLabel: root.querySelector("[data-bar-proper-label]"),
      barContractedLabel: root.querySelector("[data-bar-contracted-label]"),
      sceneStatus: root.querySelector("[data-scene-status]"),
      graph: root.querySelector("[data-lab-graph]"),
      graphDesc: root.querySelector("[data-graph-desc]"),
      curve: root.querySelector("[data-lab-curve]"),
      marker: root.querySelector("[data-lab-marker]"),
      valueBeta: root.querySelector("[data-value-beta]"),
      valueProperTime: root.querySelector("[data-value-proper-time]"),
      valueProperLength: root.querySelector("[data-value-proper-length]"),
      valueGamma: root.querySelector("[data-value-gamma]"),
      valueDilatedTime: root.querySelector("[data-value-dilated-time]"),
      valueContractedLength: root.querySelector("[data-value-contracted-length]"),
      eqGamma: root.querySelector("[data-eq-gamma]"),
      outBeta: root.querySelector("[data-out-beta]"),
      outProperTime: root.querySelector("[data-out-proper-time]"),
      outProperLength: root.querySelector("[data-out-proper-length]"),
      inputBeta: root.querySelector("[data-input-beta]"),
      inputProperTime: root.querySelector("[data-input-proper-time]"),
      inputProperLength: root.querySelector("[data-input-proper-length]"),
      btnReset: root.querySelector("[data-action-reset]")
    };

    function recompute() {
      computed = computeState(state.beta, state.properTime, state.properLength);
    }

    function setBeta(value) {
      state.beta = clampVelocityFraction(value);
      if (el.inputBeta) el.inputBeta.value = String(state.beta);
      if (el.outBeta) el.outBeta.textContent = String(state.beta);
      recompute();
      render();
    }
    function setProperTime(value) {
      state.properTime = clampProperTime(value);
      if (el.inputProperTime) el.inputProperTime.value = String(state.properTime);
      if (el.outProperTime) el.outProperTime.textContent = String(state.properTime);
      recompute();
      render();
    }
    function setProperLength(value) {
      state.properLength = clampProperLength(value);
      if (el.inputProperLength) el.inputProperLength.value = String(state.properLength);
      if (el.outProperLength) el.outProperLength.textContent = String(state.properLength);
      recompute();
      render();
    }
    function reset() {
      setBeta(0.6);
      setProperTime(10);
      setProperLength(100);
    }

    function renderScene() {
      var maxLen = Math.max(1e-9, computed.properLength);
      var baseY = 150, maxBarH = 120;
      var properH = maxBarH;
      var contractedH = (computed.contractedLength / maxLen) * maxBarH;
      if (el.barProper) {
        el.barProper.setAttribute("y", String(baseY - properH));
        el.barProper.setAttribute("height", String(properH));
      }
      if (el.barContracted) {
        el.barContracted.setAttribute("y", String(baseY - contractedH));
        el.barContracted.setAttribute("height", String(contractedH));
      }
      if (el.barProperLabel) {
        el.barProperLabel.setAttribute("y", String(baseY - properH - 6));
        el.barProperLabel.textContent = computed.properLength.toFixed(1) + " m";
      }
      if (el.barContractedLabel) {
        el.barContractedLabel.setAttribute("y", String(baseY - contractedH - 6));
        el.barContractedLabel.textContent = computed.contractedLength.toFixed(1) + " m";
      }
      var text =
        "At " + (state.beta * 100).toFixed(0) + " percent of the speed of light, a " +
        computed.properLength.toFixed(1) + " metre object measures " +
        computed.contractedLength.toFixed(1) + " metres to a stationary observer, and a " +
        computed.properTime.toFixed(1) + " second interval measures " +
        computed.dilatedTime.toFixed(1) + " seconds.";
      if (el.scene) el.scene.setAttribute("aria-label", text);
      if (el.sceneDesc) el.sceneDesc.textContent = text;
    }

    function renderGraph() {
      if (!el.curve) return;
      var w = 360, h = 190, left = 44, top = 12, bottom = 24, right = 12;
      var plotW = w - left - right, plotH = h - top - bottom;
      var samples = 60;
      var maxGamma = 1;
      var points = [];
      for (var i = 0; i <= samples; i++) {
        var b = (MAX_VELOCITY_FRACTION_C * i) / samples;
        var g = 1 / Math.sqrt(1 - b * b);
        points.push([b, g]);
        if (g > maxGamma) maxGamma = g;
      }
      var path = points.map(function (p) {
        var px = left + (p[0] / MAX_VELOCITY_FRACTION_C) * plotW;
        var py = top + plotH - (p[1] / maxGamma) * plotH;
        return px.toFixed(1) + "," + py.toFixed(1);
      }).join(" ");
      el.curve.setAttribute("points", path);
      if (el.marker) {
        var mx = left + (state.beta / MAX_VELOCITY_FRACTION_C) * plotW;
        var my = top + plotH - (computed.gamma / maxGamma) * plotH;
        el.marker.setAttribute("cx", mx.toFixed(1));
        el.marker.setAttribute("cy", my.toFixed(1));
      }
      var graphText =
        "The Lorentz factor versus velocity as a fraction of the speed of light. " +
        "It stays close to 1 for everyday speeds and rises sharply only as velocity " +
        "approaches the speed of light.";
      if (el.graph) el.graph.setAttribute("aria-label", graphText);
      if (el.graphDesc) el.graphDesc.textContent = graphText;
    }

    function render() {
      if (el.valueBeta) el.valueBeta.textContent = state.beta.toFixed(2);
      if (el.valueProperTime) el.valueProperTime.textContent = state.properTime.toFixed(1);
      if (el.valueProperLength) el.valueProperLength.textContent = state.properLength.toFixed(1);
      if (el.valueGamma) el.valueGamma.textContent = computed.gamma.toFixed(3);
      if (el.valueDilatedTime) el.valueDilatedTime.textContent = computed.dilatedTime.toFixed(2);
      if (el.valueContractedLength) el.valueContractedLength.textContent = computed.contractedLength.toFixed(2);
      if (el.eqGamma) el.eqGamma.textContent = computed.gamma.toFixed(3);
      renderScene();
      renderGraph();
      root.dispatchEvent(new CustomEvent("lab:state", { detail: getState() }));
    }

    function getState() {
      return {
        velocityFractionC: state.beta,
        properTimeS: state.properTime,
        properLengthM: state.properLength,
        lorentzFactor: computed.gamma,
        dilatedTimeS: computed.dilatedTime,
        contractedLengthM: computed.contractedLength,
        running: false
      };
    }

    if (el.inputBeta) {
      el.inputBeta.addEventListener("input", function () { setBeta(el.inputBeta.value); });
      el.inputBeta.addEventListener("change", function () { setBeta(el.inputBeta.value); });
    }
    if (el.inputProperTime) {
      el.inputProperTime.addEventListener("input", function () { setProperTime(el.inputProperTime.value); });
      el.inputProperTime.addEventListener("change", function () { setProperTime(el.inputProperTime.value); });
    }
    if (el.inputProperLength) {
      el.inputProperLength.addEventListener("input", function () { setProperLength(el.inputProperLength.value); });
      el.inputProperLength.addEventListener("change", function () { setProperLength(el.inputProperLength.value); });
    }
    if (el.btnReset) el.btnReset.addEventListener("click", reset);

    recompute();
    render();

    var api = {
      setBeta: setBeta,
      setProperTime: setProperTime,
      setProperLength: setProperLength,
      reset: reset,
      getState: getState
    };
    root.labInstance = api;
    return api;
  }

  PhysicsLab.register("time_dilation", createTimeDilationSim);

  PhysicsLab.TimeDilation = {
    MIN_VELOCITY_FRACTION_C: MIN_VELOCITY_FRACTION_C,
    MAX_VELOCITY_FRACTION_C: MAX_VELOCITY_FRACTION_C,
    MIN_PROPER_TIME_S: MIN_PROPER_TIME_S,
    MAX_PROPER_TIME_S: MAX_PROPER_TIME_S,
    MIN_PROPER_LENGTH_M: MIN_PROPER_LENGTH_M,
    MAX_PROPER_LENGTH_M: MAX_PROPER_LENGTH_M,
    clampVelocityFraction: clampVelocityFraction,
    clampProperTime: clampProperTime,
    clampProperLength: clampProperLength,
    computeState: computeState
  };
})(window, document);
